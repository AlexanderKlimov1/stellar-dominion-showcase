package com.sddnw.server.service;

import com.sddnw.server.domain.enums.GalaxySize;
import com.sddnw.server.dto.CreateGameRequest;

import java.util.List;

/**
 * Гостевая партия — backlog-promo, пункт 1 (решение хозяина проекта).
 * <p>
 * <b>Зачем.</b> До первой партии зарегистрированному игроку нужно четыре шага (форма,
 * задачка, письмо, ссылка), и каждый отсекает долю пришедших по ссылке раньше, чем они
 * увидели игру. Гость получает партию одним нажатием, а регистрация остаётся тем, кому
 * есть что терять.
 * <p>
 * <b>Настройки назначает сервер, а не окно новой игры</b>: малая галактика, четыре
 * империи (гость и три ИИ), совет, удержание Wardenhold и итог по могуществу на
 * трёхсотом ходу как пути к победе, а покорение действует всегда. Короткая партия с ясной
 * целью — это то, что новичок доигрывает; Huge против семерых — марафон, который он бросит. Расу, знамя и имена гость выбирает сам:
 * это самая весёлая часть входа в партию, и отнимать её незачем.
 * <p>
 * <b>Родные миры стоят тесно</b> (backlog-promo, пункт 5, решение хозяина проекта): замер
 * показал первое знакомство на 125–183-м ходу — ИИ к пятидесятому ходу из родной системы не
 * выходит, а миры малой галактики, разнесённые по углам, стоят в десяти парсеках при
 * дальности в четыре. Для первой партии новичка это полторы сотни ходов без соседей. Признак
 * ставит {@code GameController}, правило расстановки — {@code HomeworldAllocator}.
 * <p>
 * Правило стоит на сервере, потому что клиент лишь ПРЕДЛАГАЕТ: запрос гость шлёт сам, и
 * огромную галактику на восьмерых он заказал бы одной строкой.
 */
public final class GuestGameRules {

    /** Галактика гостя: тридцать три звезды — партия доигрывается за вечер. */
    public static final GalaxySize GALAXY = GalaxySize.SMALL;

    /** Империй в партии гостя: он сам и три ИИ. */
    public static final int EMPIRES = 4;

    /**
     * Уровни, изученные с первого хода (backlog-promo, пункт 15, решение хозяина проекта):
     * двигатель и химия — то, без чего не строится ни один корабль. Ссылками «раздел:номер»,
     * как и стартовые уровни справочника. В прочих партиях их исследуют (с 01.10.2026), а
     * гостю нужно, чтобы с первого хода было чем ходить.
     */
    public static final List<String> STARTING_LEVELS = List.of("power:1", "chemistry:1");

    /**
     * Уровни дерева до этого включительно изучаются в гостевой партии СРАЗУ ПО ОПЛАТЕ, без
     * случайной вилки до двойной цены (backlog-promo, пункт 25, решение хозяина проекта):
     * первая технология шла 13–26 ходов, и начало первой партии тонуло в пустых ходах.
     * Дальше прорыв случаен, как во всякой партии, — к тому времени игроку есть чем заняться.
     */
    public static final int INSTANT_LEVELS = 3;

    /** Корпус стартовых разведчиков и их число — как пара разведчиков MOO II. */
    public static final String SCOUT_HULL = "frigate";
    public static final int STARTING_SCOUTS = 2;


    private GuestGameRules() {
    }

    /** Запрос гостя с настройками, которые назначает сервер; выбор расы и имён остаётся его. */
    public static CreateGameRequest restrict(CreateGameRequest request) {
        return new CreateGameRequest(
                request.name(),
                GALAXY,
                request.playerName(),
                request.homeStarName(),
                request.raceCode(),
                request.raceName(),
                request.raceTraits(),
                // Зерно гостю не назначается: оно нужно прогонам, а не игре.
                null,
                // События — часть игры, как в оригинале: гостю их не выключить.
                Boolean.TRUE,
                // Гость играет сам: наблюдать за партией ИИ — это проверка, а не игра.
                Boolean.FALSE,
                EMPIRES,
                // Совет — один из трёх путей к победе.
                Boolean.TRUE,
                Boolean.TRUE,
                request.banner(),
                // Удержание Wardenhold — третий путь, ради которого гостевая партия и короткая.
                Boolean.TRUE,
                // Итог по могуществу: партия гостя кончается всегда, даже если ни один
                // путь не сработал.
                Boolean.TRUE,
                // Срок хода гостю не нужен: он играет один, и ждать его некому.
                null);
    }
}
