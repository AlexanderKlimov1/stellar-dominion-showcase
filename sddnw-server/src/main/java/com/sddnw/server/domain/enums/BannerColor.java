package com.sddnw.server.domain.enums;

import java.util.Arrays;
import java.util.Optional;

/**
 * Знамя империи — её цвет на карте, в списках и на поле боя, п. 3.2.
 * <p>
 * <b>Выбирает его игрок перед началом партии, как в MOO II</b> (01.10.2026, решение хозяина
 * проекта): после выбора расы оригинал показывает восемь знамён — красное, жёлтое, зелёное,
 * серебряное, синее, коричневое, фиолетовое и оранжевое, — и занятое другим игроком взять
 * нельзя. Восемь — ровно столько, сколько империй бывает в партии, поэтому цвета хватает
 * всем, и ИИ разбирает оставшиеся.
 * <p>
 * Прежде цвет империи был цветом её РАСЫ, и этого было мало дважды: двое игроков одной
 * расы получали один цвет, а у тринадцати рас оттенки перекликаются (два синих, два
 * фиолетовых, два бирюзовых), и разных соседей на карте было не различить.
 * <p>
 * Оттенки шести знамён совпадают с цветами рас оригинала, которые им и соответствуют
 * (Земляне синие, Церебри красные, Читарри зелёные…): ИИ берёт знамя своей расы, если оно
 * свободно, и привычные цвета соседей сохраняются. Хранится у игрока по-прежнему строка
 * цвета — знамя лишь выбирает её из восьми.
 */
public enum BannerColor {
    RED("#ff5f5f"),
    YELLOW("#ffd447"),
    GREEN("#57d977"),
    SILVER("#c9d1dc"),
    BLUE("#4fa3ff"),
    BROWN("#b07a4a"),
    PURPLE("#b56cff"),
    ORANGE("#ff9a3c");

    private final String hex;

    BannerColor(String hex) {
        this.hex = hex;
    }

    /** Цвет знамени строкой `#rrggbb` — так он хранится у игрока и уходит клиенту. */
    public String hex() {
        return hex;
    }

    /** Знамя по цвету; пусто — цвет не из восьми (раса без своего знамени, старая партия). */
    public static Optional<BannerColor> ofHex(String hex) {
        return Arrays.stream(values()).filter(banner -> banner.hex.equalsIgnoreCase(hex)).findFirst();
    }
}
