package com.sddnw.server.dto;

import jakarta.validation.constraints.NotNull;

import java.util.Map;

/**
 * Раскладка горячих клавиш карты — п. 11.1: «действие: клавиша»
 * ({@code {"turn": "KeyT", "colonies": "KeyC"}}).
 * <p>
 * Уходит ЦЕЛИКОМ, а не по одной паре — даже когда игрок переназначил одну клавишу:
 * присылать «одно действие» значило бы держать на сервере порядок применения правок и
 * гадать, что делать с действием, которого в присланном нет. Раскладка целиком отвечает на
 * оба вопроса сама.
 * <p>
 * <b>Значения этих пар сервер не толкует.</b> Какие действия у карты есть и какие клавиши
 * им годятся — дело клиента ({@code ui/hotkeys.ts}); сервер по горячей клавише не делает
 * ничего. Поэтому служба проверяет только ВИД записи (сколько пар и из чего состоят их
 * имена), а списка действий здесь нет: он стал бы второй правдой, которая молча отстанет
 * от первой.
 */
public record HotkeysRequest(
        @NotNull Map<String, String> hotkeys
) {
}
