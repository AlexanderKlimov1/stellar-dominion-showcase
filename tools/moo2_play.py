def open_game_menu(game):
    """
    Открывает меню игры и УБЕЖДАЕТСЯ, что оно открылось; пусто — не вышло.

    Одного нажатия мало: в одной пробе меню открылось, в следующей — нет, курсор стоял на
    плашке, а меню не было. Виноват, похоже, возврат фокуса: `probe.focus` на второй
    попытке нажимает ALT, а ALT такие меню и закрывает. Поэтому смотрим на результат, а не
    верим нажатию: в открытом меню на месте кнопки «SAVE GAME» есть текст, на карте там
    звёздное небо и текста нет.
    """
    for attempt in range(3):
        game.tap(GAME_MENU, wait=1.4)
        image = game.look()
        view = text.game_view(image).convert('L')
        x, y, width, height = GAME_MENU_PROOF
        points = list(view.crop((x, y, x + width, y + height)).getdata())
        lit = sum(points) / float(len(points))
        game.say('    меню игры, попытка %d: яркость на месте кнопки %.1f (порог %d)'
                 % (attempt + 1, lit, GAME_MENU_LIT))
        if lit >= GAME_MENU_LIT:
            return image
    return None


def trim_farmers(game, name):
    """
    Снимает ЛИШНЕГО фермера и отправляет его в науку — п. решения хозяина проекта 23.09.2026.

    ЗАЧЕМ. Плюс по еде — это не запас, а простаивающий житель: съесть его нельзя, продать
    нельзя, лежит он мёртвым грузом. Держим ноль или минимальный плюс, а освободившихся
    отдаём науке — на старте она решает всё.

    ПОЧЕМУ ПО ОДНОМУ ЗА ЗАХОД, а не «сколько плюса, столько и фермеров». Еда считается по
    ВСЕЙ ИМПЕРИИ, а снимаем мы с одной колонии, и фермер даёт не одну единицу, а две-три
    смотря по планете. Сняв всех разом, империю легко уронить в голод — а голод убивает
    жителя каждый ход. По одному за заход это сходится за несколько ходов и не
    перелетает: колонии теперь осматриваются КАЖДЫЙ ход, а если всё же перелетели,
    следующий же заход вернёт фермера обратно (`feed_colony`). Число «сколько даёт
    фермер» нигде на экране не написано, поэтому осторожность тут дешевле точности.
    """
    counted = count_jobs(game.look())
    if counted[0][1] <= 0:
        return 0
    after, way = try_move(game, name, 0, 2, counted)
    if not way:
        game.say('    %s: снять лишнего фермера не вышло (было %s, стало %s)'
                 % (name, [job[1] for job in counted], [job[1] for job in after]))
        return 0
    game.say('    %s: еды с избытком — фермер ушёл в науку (стало %s)'
             % (name, [job[1] for job in after]))
    return 1


def hunger_depth(totals):
    """
    Насколько глубока яма по еде: столько жителей и переводим.

    Читается число не всегда (строку заслоняет объявление, шрифт мелкий), поэтому
    непрочитанная еда значит ОДИН житель, а не ноль: голод виден по минусу в строке и без
    числа, и не сделать ничего хуже, чем сделать один шаг.
    """
    food = totals.get('food')
    if food is None or food >= 0:
        return 1
    return max(1, -food)


def count_jobs(image):
    """
    Сколько жителей в каждом ряду занятий и где они стоят.

    Считаются НЕ ПЯТНА, а ПЛОТНЫЕ СТОЛБЦЫ. Фон ряда — звёздное небо, и по пятнам звёзды
    шли в счёт наравне с людьми: у колонии с четырьмя фермерами выходило семнадцать. А
    фигурка жителя — это столбик в два десятка точек высотой, тогда как звезда занимает
    одну-две: разница на порядок, и порог по ней проводится надёжно.

    Отдаёт по ряду: имя, сколько жителей, точки каждого.
    """
    counted = []
    for name, row in JOB_ROWS:
        top = row - JOB_ROW_HEIGHT // 2
        mask, offset_x, offset_y, width, height = text._mask(
            image, (JOB_FIRST_X - 12, top, JOB_ROW_WIDTH, JOB_ROW_HEIGHT), JOB_BRIGHT)
        dense = [sum(1 for line in mask if line[column]) >= JOB_COLUMN_DOTS
                 for column in range(width)]
        spots = []
        run = 0
        for column in range(width + 1):
            if column < width and dense[column]:
                run += 1
                continue
            if run >= JOB_COLUMN_RUN:
                spots.append((offset_x + column - run // 2, row))
            run = 0
        counted.append((name, len(spots), spots))
    return counted


#: Насколько светла точка фигурки жителя: одежда светлее неба за ней.
JOB_BRIGHT = 110

#: Сколько светлых точек в столбце делают его частью фигурки, а не звездой фона.
JOB_COLUMN_DOTS = 6

#: Сколько плотных столбцов подряд составляют фигурку: звезда даёт один-два.
JOB_COLUMN_RUN = 4


def feed_colony(game, name, need=1):
    """
    Переводит жителей на еду, пока колония голодает, — п. 4.1.1 нашего README.

    СКОЛЬКО переводить, говорит нехватка еды по империи (`need`): яму в три единицы одним
    жителем не закрыть, а прежде инструмент переводил ровно одного и уходил — цикл на
    четыре попытки стоял, но обе его ветки возвращали ответ на первом же круге, так что
    повторов не случалось НИ РАЗУ. Отсюда и то, что колония голодала с первых ходов и
    дальше: за каждый заход она отыгрывала одну единицу еды, а теряла больше.

    Перевод одного жителя даёт разное число еды (фермер на бедной планете кормит хуже),
    поэтому «сколько жителей» из «сколько еды» выводится ОДИН К ОДНОМУ — это
    реконструкция, и она нарочно осторожная: перевести лишнего дешевле, чем недокормить,
    а следующий заход всё равно посмотрит на еду заново.

    ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ СТРОЙКИ. Голод в MOO II убивает жителей КАЖДЫЙ ХОД, а
    гидропонная ферма строится десяток ходов; к её достройке кормить будет уже некого.
    Наш ИИ этого не знает, потому что у него голода почти не бывает: он расставляет
    жителей сам (`ColonyService`), и еда считается до всякой стройки. Инструмент же играет
    руками, и у него есть ровно то же средство, что у человека, — перетащить фигурку из
    ряда в ряд.

    Забираем у ТОГО РЯДА, ГДЕ ЖИТЕЛЕЙ БОЛЬШЕ, — это и есть «минимизировать ущерб»: у
    многолюдного ряда один житель значит меньше. Переводим по одному и смотрим снова:
    сколько нужно, столько и переведём, а лишнего не отнимем.
    """
    if name in game.unfeedable:
        game.say('    %s: фермы тут не ставятся — кормить нечем, пропускаем' % name)
        return False
    moved = 0
    for _attempt in range(max(1, need)):
        image = game.look()
        counted = count_jobs(image)
        farmers = counted[0]
        donors = [job for job in counted[1:] if job[1] > 0]
        if not donors:
            game.say('    %s: голод, а забрать жителя не у кого' % name)
            return moved > 0
        donor = max(donors, key=lambda job: job[1])
        spot = donor[2][-1]
        target = (JOB_FIRST_X + farmers[1] * JOB_STEP, JOB_ROWS[0][1])
        # Тащим только МЕЖДУ РОДАМИ ЗАНЯТИЙ: перестановка внутри ряда игрой не
        # засчитывается, а стоит целого захода.
        if abs(spot[1] - target[1]) < JOB_ROW_HEIGHT:
            game.say('    %s: донор и фермеры оказались одним рядом — не тащим' % name)
            return moved > 0
        game.say('    %s: голод — %s отдают жителя фермерам (было %d, нужно ещё %d); '
                 'тащим %s -> %s'
                 % (name, donor[0], donor[1], max(1, need) - moved, spot, target))
        after, way = try_move(game, name, counted.index(donor), 0, counted)
        if not way:
            # Счёт по рядам пишем целиком: «не вышло» без чисел не отличает промах мимо
            # ряда от игры, которая перевод не разрешила, — а это разные поломки.
            game.say('    %s: перевести жителя не вышло ни одним способом '
                     '(было %s, стало %s)'
                     % (name, [job[1] for job in counted], [job[1] for job in after]))
            # И БОЛЬШЕ К ЭТОЙ КОЛОНИИ С ЕДОЙ НЕ ХОДИМ. Причина обычно одна и навсегда: в
            # списке колоний у такой планеты в столбце фермеров стоит «No Farming» —
            # радиоактивный или мёртвый мир, где ферму не поставить вовсе (замерено на
            # `Sol II`, Medium Radiated). Пока памяти не было, инструмент ломился туда
            # каждый ход: открыть колонию, поднять жителя, положить обратно — и так до
            # конца партии. Память живёт ЗАПУСК, а не партию: население планеты меняется,
            # и упереться мы могли и в потолок ряда, а не в саму планету.
            game.unfeedable.add(name)
            return moved > 0
        moved += 1
    game.say('    %s: переведено на еду жителей: %d' % (name, moved))
    return moved > 0


def buy_project(game, book, what, credits):
    """
    Выкупает стройку за кредиты по правилу нашего ИИ (`AiEmpireService.buyProject`).

    Оттуда же и потолок цены: на ОСНОВАНИЕ (завод и лаборатория) кладётся вся казна — эти
    здания доход поднимают, купив их, империя бережёт резерв, а не проедает; на всё
    прочее — половина казны, чтобы осталось на содержание. Покупка ОДНА за заход, как одна
    за ход у нашего ИИ: казна общая.

    Цена читается из самого вопроса игры («Do you want to spend 160 BC to buy 80
    production?»), а не считается по своей формуле: своя формула разошлась бы с чужой игрой
    в первый же день.
    """
    if any(rules.matches(what, endless) for endless in rules.ENDLESS):
        return False
    limit = credits if any(rules.matches(what, base) for base in rules.FOUNDATION) \
        else (credits or 0) // 2
    game.tap(COLONY_BUY, wait=1.4)
    name, image = game.scene(book)
    if name != 'buy-confirm':
        return False
    asked = None
    for line in text.read(image, BUY_QUESTION):
        asked = asked if asked is not None else number(line['text'])
    if asked is not None and limit and asked > limit:
        game.say('    выкуп «%s» за %d кредитов отложен: потолок %d' % (what, asked, limit))
        game.tap(BUY_NO, wait=1.4)
        return False
    game.tap(BUY_YES, wait=1.6)
    game.say('    выкупили «%s»%s'
             % (what, '' if asked is None else ' за %d кредитов' % asked))
    return True


def manage_one(game, book, name, spot, totals, buy_if, want_freighters):
    """Одна колония: назначить стройку по правилам ИИ, выкупить её и вернуться в список."""
    game.tap(spot, wait=1.4)
    # ЕДА ВПЕРЁД ВСЕГО, и вперёд даже выбора стройки: голод убивает жителей каждый ход,
    # а стройка — дело десятка ходов.
    if totals.get('hungry'):
        feed_colony(game, name, hunger_depth(totals))
    elif (totals.get('food') or 0) >= FOOD_SURPLUS_TO_TRIM:
        # Плюс по еде — это простаивающий житель, и он нужнее в лаборатории. Но снимаем
        # только с ИЗБЫТКА, а не с любого плюса: порог здесь тот же, что и в дешёвом
        # заходе, и стоит он не для порядка. Пока тут было «больше нуля», колония качалась
        # маятником каждый ход: еда +1 — снимаем фермера — еда −1 — возвращаем — снова +1.
        # Фермер даёт две единицы, поэтому из плюс единицы снятие ВСЕГДА роняет в минус, а
        # плюс единица — это и есть «минимальный необходимый уровень», который просили
        # держать.
        trim_farmers(game, name)
    # И только потом наука. Порядок тут не вкусовой: голод отнимает жителя каждый ход, а
    # наука — это ходы, которых не хватит потом. Признак берём из памяти партии
    # (`game.taken`), а не из списка стройки: список ещё не открыт, а память переживает и
    # ход, и перезапуск.
    if not FOUNDATION_KNOWN <= game.taken:
        push_research(game, name)
    game.tap(COLONY_CHANGE, wait=1.4)
    image = game.look()
    # Список стройки читается СРАЗУ и у любой колонии — занятой тоже. Он единственное
    # доказательство изученного, какое у инструмента есть: колониальный корабль в нём
    # значит, что двигатель получен, завод — что получена его технология. Пока его читали
    # только у свободных колоний, память партии оставалась пустой — колонии подолгу
    # строили базы, и наука заново гналась за двигателем, который давно в руках.
    offered = game.rows(image, BUILD_LEFT) + game.rows(image, BUILD_RIGHT)
    known = len(game.taken)
    rules.note_proofs(offered, game.taken)
    if len(game.taken) != known:
        save_state(game.taken, game.wanted)
    queue = queue_rows(game, image)
    busy = queue and not any(rules.matches(queue[0][0], endless)
                             for endless in rules.ENDLESS)
    if busy:
        # Колония уже занята делом — не трогаем. Иначе заход раз в несколько ходов
        # сбрасывал бы длинную стройку в начало: очередь чистится целиком, а вложенное в
        # неё пропадает. У нашего ИИ то же правило: пересматривают дело только колонии на
        # товарах и на домах.
        what = queue[0][0]
        # ИСКЛЮЧЕНИЕ ОДНО: появился завод — бросаем базу и берёмся за него.
        #
        # Решение хозяина проекта 23.09.2026, и держится оно на том, что накопленные
        # колонией единицы производства НЕ ПРОПАДАЮТ при смене стройки: всё, что вложено в
        # колониальную базу за двенадцать ходов ожидания, уходит заводу, и завод встаёт
        # почти готовым. Поэтому база и разрешена до завода (`moo2_rules.choose_project`):
        # пока науки нет, колония не ждёт на домах, а копит.
        #
        # Меняем только базу и только на основание. Всякую другую стройку по-прежнему не
        # трогаем: заход раз в несколько ходов иначе сбрасывал бы в начало длинную стройку,
        # которую никто не просил менять.
        upgrade, where = (rules.first(rules.FOUNDATION, offered)
                          if rules.matches(what, rules.COLONY_BASE) else (None, None))
        if upgrade:
            game.say('    %s: «%s» уступает место — строим «%s», вложенное уходит ему'
                     % (name, what, upgrade))
            clear_queue(game)
            game.tap(where, wait=0.6)
            game.tap(BUILD_OK, wait=1.2)
            what = upgrade
        else:
            game.say('    %s: уже строит «%s» — не мешаем' % (name, what))
            game.tap(BUILD_CANCEL, wait=1.2)
    else:
        # Основание ещё не в руках, если хоть одна из двух нужд не закрыта: закрытая
        # значит, что здание видели в списке стройки, то есть технология изучена.
        pending = not FOUNDATION_KNOWN <= game.taken
        what, where, why = rules.choose_project(offered, totals.get('hungry', False),
                                                want_freighters,
                                                game.warships < rules.SCOUTS_AT_ONCE,
                                                pending)
        if what:
            game.say('    %s: строим «%s» — %s' % (name, what, why))
            clear_queue(game)
            game.tap(where, wait=0.6)
            game.tap(BUILD_OK, wait=1.2)
        else:
            game.say('    %s: %s (%s)'
                     % (name, why, '; '.join(seen for seen, _ in offered) or 'пусто'))
            game.tap(BUILD_CANCEL, wait=1.2)
    bought = False
    if what and buy_if(what):
        bought = buy_project(game, book, what, totals.get('credits'))
    game.tap(COLONY_RETURN, wait=1.4)
    return what, bought


