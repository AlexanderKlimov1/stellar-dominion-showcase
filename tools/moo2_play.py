def place_colony_base(game, book):
    """
    Сажает готовую колониальную базу на планету своей системы — п. 4.1 нашего README.

    Игра сама открывает окно «Select planet for Colony Base» со схемой системы: базу
    строили десяток ходов, и не посадить её значит выбросить их. Планеты ищутся по
    картинке (`moo2_map.planets`), а выбор идёт ПЕРЕБОРОМ от крупной к мелкой: крупная
    планета вмещает больше жителей, а какие из них вообще пригодны, знает только игра —
    на непригодную она просто не отзовётся, и окно останется открытым. Это и есть
    проверка: окно закрылось — база села.
    """
    image = game.look()
    targets = chart.planets(image)
    if not targets:
        game.say('    базу сажать некуда: планет на схеме не видно')
        game.tap(BASE_TARGET_CLOSE, wait=1.4)
        return False
    for target in targets:
        game.tap(target['spot'], wait=1.6)
        name, _ = game.scene(book)
        if name != 'colony-base-target':
            game.say('    колониальная база села на планету в точке %s' % (target['spot'],))
            return True
    game.say('    ни одна из %d планет базу не приняла' % len(targets))
    game.tap(BASE_TARGET_CLOSE, wait=1.4)
    return False


