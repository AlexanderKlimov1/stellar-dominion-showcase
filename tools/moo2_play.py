def to_minimap(spot):
    """
    Точка большой карты — в точку мини-карты окна флота.

    Пересчёт ЛИНЕЙНЫЙ и это реконструкция: обе карты показывают галактику целиком, поэтому
    прямоугольники просто растягиваются друг в друга. Держится это на том, что инструмент
    никогда не меняет масштаб большой карты (кнопок ZOOM он не нажимает). Начнёт менять —
    пересчёт соврёт, и первым это увидит журнал: он пишет обе точки.
    """
    x, y = spot
    fx, fy, fw, fh = chart.FIELD
    mx, my, mw, mh = FLEET_MINIMAP
    return (int(mx + (x - fx) * mw / float(fw)),
            int(my + (y - fy) * mh / float(fh)))


#: Каким цветом игра рисует значок нашего флота на карте.
#:
#: Замерено по `tools/moo2-scenes/fleet-on-map.png`: у звезды Sol стоит зелёный значок из
#: пяти точек с самым ярким зелёным 203, и во всём поле карты таких сгустков РОВНО ДВА —
#: обе половины этого значка. Звёзды белые, красные, синие и оранжевые, под порог не
#: подходят; имена систем тоже зелёные, но тусклее (около 145), и порог 160 их отсекает.
#: Каким зелёным написан ТЕКСТ окна флота: (44, 130, 36), замерено по снимкам.
#:
#: Он тусклее значка флота на карте (там зелёный доходит до 203), и это не придирка: под
#: порогом значка окно не находилось вовсе.
DIALOG_GREEN = 110
DIALOG_OVER_RED = 60

#: Где у окна кнопки — ОТ ЕГО ЗАГОЛОВКА, а не от края экрана.
#:
#: Окно ходит по карте: оно встаёт подальше от самого флота, и у звезды в левом нижнем углу
#: появляется справа вверху, и наоборот. Постоянные координаты били мимо — ни ALL, ни CLOSE
#: не нажимались, окно оставалось открытым, а приказ уходил в никуда. Числа замерены по двум
#: снимкам с окном в РАЗНЫХ углах и совпали до точки.
PICK_ALL_FROM_TITLE = (-15, 80)
PICK_CLOSE_FROM_TITLE = (0, 119)


def fleet_dialog_title(image):
    """
    Где стоит заголовок «Human Fleet» окна отбора; пусто — окна на экране нет.

    Ищется он своим зелёным и берётся самым крупным сгустком: у заголовка своих точек
    больше четырёх сотен, тогда как у зелёного имени системы на карте — несколько десятков.
    """
    view = text.game_view(image).convert('RGB')
    x0, y0, width, height = chart.FIELD
    pixels = view.load()
    points = []
    for row in range(y0, y0 + height):
        for col in range(x0, x0 + width):
            red, green, blue = pixels[col, row]
            if (green >= DIALOG_GREEN and green - red >= DIALOG_OVER_RED
                    and green - blue >= DIALOG_OVER_RED):
                points.append((col, row))
    groups = []
    for col, row in points:
        for group in groups:
            if any(abs(col - gc) <= 70 and abs(row - gr) <= 70 for gc, gr in group[-20:]):
                group.append((col, row))
                break
        else:
            groups.append([(col, row)])
    if not groups:
        return None
    best = max(groups, key=len)
    if len(best) < 150:
        return None
    return (min(p[0] for p in best), min(p[1] for p in best),
            max(p[0] for p in best), max(p[1] for p in best))

#: Насколько цель должна отстоять от нашего же значка флота, чтобы считаться целью.
#: Значок стоит вплотную к своей звезде, поэтому три десятка точек отсекают и его, и её.
NOT_OURSELVES = 30

FLEET_GREEN = 160
FLEET_OVER_RED = 50


def fleet_icons(image):
    """
    Где на карте стоят значки нашего флота: зелёные сгустки.

    Искать их размером нельзя — у значка и у звезды он один и тот же (12–200 точек по
    мерке `moo2_map`), и значок без имени под ним сходил бы за неразведанную звезду.
    Цвет разделяет их надёжно и дёшево.
    """
    view = text.game_view(image).convert('RGB')
    x0, y0, width, height = chart.FIELD
    pixels = view.load()
    lit = []
    for row in range(y0, y0 + height):
        for col in range(x0, x0 + width):
            red, green, blue = pixels[col, row]
            if (green >= FLEET_GREEN and green - red >= FLEET_OVER_RED
                    and green - blue >= FLEET_OVER_RED):
                lit.append((col, row))
    # Точки одного значка лежат кучно; разводим их по сгусткам простым соседством.
    icons = []
    for col, row in lit:
        for icon in icons:
            if abs(icon[0][0] - col) <= 12 and abs(icon[0][1] - row) <= 12:
                icon.append((col, row))
                break
        else:
            icons.append([(col, row)])
    return [(sum(p[0] for p in one) // len(one), sum(p[1] for p in one) // len(one))
            for one in icons]


def send_fleets(game, book, image):
    """
    Шлёт флот к неразведанной звезде — дорогой ОРИГИНАЛА, названной хозяином проекта.

    Порядок такой: нажать на карте пиктограмму флота (зелёный треугольник у своей звезды),
    в открывшемся окне отобрать корабли, закрыть окно — и СЛЕДУЮЩИМ нажатием указать
    звезду назначения. Координаты при этом обычные, карты: пересчитывать ничего не надо.

    ПРЕЖНИЙ ПУТЬ БЫЛ НЕВЕРЕН. Отправка делалась через окно FLEET OPERATIONS кнопками ALL и
    RELOCATE; окно послушно включало режим и показывало в поле назначения «unexplored», а
    флот не двигался с места — за две партии ни одного перелёта. Хуже того, сетка кораблей
    в том окне была пуста, и распознать это было нечем.

    Окна отбора кораблей я ещё не видел, поэтому первый его показ ОТКЛАДЫВАЕТСЯ СНИМКОМ, а
    закрыть его пробуем самым безобидным — Esc. Выйдет — отправка состоится; не выйдет —
    снимок скажет, на что нажимать, и это будет знание, а не догадка.
    """
    if not game.warships:
        return False
    icons = fleet_icons(image)
    targets = chart.unexplored(image)
    if not icons or not targets:
        return False
    icon = icons[0]
    # ЦЕЛЬ НЕ ДОЛЖНА БЫТЬ РЯДОМ С НАМИ, и это не вкус, а починка. «Неразведанная звезда» —
    # это значок без имени под ним, а под наш ЗЕЛЁНЫЙ ЗНАЧОК ФЛОТА имени тоже нет, и стоит
    # он у своей звезды. Оттого ближайшей целью выходил он сам или его звезда: приказ
    # получался «лететь в себя», игра принимала нажатие за осмотр и открывала окно системы
    # («Star System Sol»). Я эту опасность назвал, когда писал поиск по цвету, но заслона
    # не поставил — вот он.
    far = [one for one in targets
           if all(abs(one['spot'][0] - spot[0]) > NOT_OURSELVES
                  or abs(one['spot'][1] - spot[1]) > NOT_OURSELVES for spot in icons)]
    if not far:
        game.say('    все неразведанные цели — рядом с нашим же флотом, не шлём')
        return False
    target = chart.nearest(icon, far)
    game.say('    флот у %s -> шлём к неразведанной звезде %s (значков %d, целей %d)'
             % (icon, target['spot'], len(icons), len(targets)))

    game.tap(icon, wait=1.4)
    # Окно отбора: заголовок «Human Fleet», ячейки кораблей, кнопка ALL и CLOSE внизу.
    # Координаты сняты с `tools/moo2-scenes/fleet-dialog.png`. Сперва тут стоял Esc — он
    # окно и закрывал, но НИЧЕГО НЕ ОТБИРАЛ, и отправки не выходило: игре нужно сказать,
    # какие корабли летят. Берём все: разведчику незачем дробить флот.
    title = fleet_dialog_title(game.look())
    if title is None:
        game.say('    окно отбора кораблей не открылось — приказ отменён')
        return False
    left, _top, right, bottom = title
    # «ALL» НЕ НАЖИМАЕМ: корабли в окне отобраны СРАЗУ, а кнопка эта — переключатель.
    #
    # Измерено двумя снимками, до и после нажатия: синева ячеек падала с 255 до 105, то
    # есть отбор СНИМАЛСЯ. Окно закрывалось с пустыми руками, и следующее нажатие по звезде
    # игра принимала за осмотр — всплывала справка «Star System Unexplored» вместо приказа.
    # Ровно это и происходило две попытки подряд, пока я правил то координаты, то Esc.
    game.tap(((left + right) // 2 + PICK_CLOSE_FROM_TITLE[0],
              bottom + PICK_CLOSE_FROM_TITLE[1]), wait=1.0)
    game.tap(target['spot'], wait=1.8)
    # Проверить, полетел ли флот, нам нечем, кроме карты: летящий значок уходит со звезды.
    # Поэтому откладываем снимок ПОСЛЕ приказа — один раз, для разбора.
    if not getattr(game, 'fleet_after_shot', False):
        game.fleet_after_shot = True
        where = os.path.join(probe.SCENES_DIR, 'fleet-after.png')
        game.look().save(where)
        game.say('    карта после приказа отложена: %s' % where)
    return True


def is_colony_name(said):
    """
    Настоящее ли это название колонии — или пустая строка списка.

    ЗАЧЕМ. Список колоний в MOO II разлинован на десяток строк, и пустые тоже обведены
    рамкой. На пороге, каким читаются имена, эта разлиновка иногда даёт «буквы», и
    инструмент насчитал ПЯТЬ колоний там, где их было две: три лишних — пустые строки,
    прочитанные как «? ? ?». Дальше он честно ходил по ним, открывал пустоту и тратил на
    это ходы.

    Отличаются они просто: у настоящего названия есть читаемые буквы. Строка из одних
    вопросительных знаков и пробелов — это не имя, а рамка.
    """
    letters = [sign for sign in said if sign not in ' ?']
    return len(letters) >= 2


def visit_colonies(game, book, names, what):
    """
    Заход по колониям ради ОДНОГО дела: у каждой открыть экран, сделать и вернуться.

    Кого именно это касается, инструменту неизвестно — еда в MOO II считается по всей
    империи, и в списке колоний стоит одно число на всех. Поэтому обходим всех.
    """
    for name, spot in names:
        game.tap(spot, wait=1.4)
        what(game, name)
        for _attempt in range(3):
            where, _ = game.scene(book)
            if where == 'colonies':
                break
            if where == 'colony':
                game.tap(COLONY_RETURN, wait=1.4)
            else:
                return


def manage_colonies(game, book, builds=True):
    """
    Обходит ВСЕ колонии списка: у каждой своя стройка, на всю империю — одна покупка.

    Первая колония — не единственная, и это не мелочь: расселение начинается с того, что
    новая колония строит своё, а не стоит на товарах.

    ДВА ДЕЛА ЗДЕСЬ РАЗВЕДЕНЫ, и не зря. Стройку пересматривают раз в несколько ходов
    (`BUILD_EVERY`): она длится десяток ходов, и открывать колонии каждый ход — значит
    тратить полминуты впустую. А голод убивает жителей КАЖДЫЙ ХОД, и раз в пять ходов его
    лечить нельзя: за четыре хода ожидания колония теряет больше, чем отыгрывает один
    переведённый житель. Поэтому с `builds=False` заход дешёвый — открыть список,
    прочитать сводку и уйти; в колонии он лезет, только если империя и правда голодает.
    """
    game.tap(MAP_COLONIES, wait=1.6)
    image = game.look()
    names = [row for row in game.rows(image, COLONIES_NAMES, bright=COLONIES_BRIGHT)
             if is_colony_name(row[0])]
    totals = empire_totals(game, image)
    # Казну запоминаем на игре: при встрече с лидером своего числа на экране нет, а решать
    # «хватает ли» надо именно там.
    if totals.get('credits') is not None:
        game.credits = totals['credits']
    # Ждём ли мы подтверждения найма из запаса — теперь есть с чем сравнить.
    if game.hiring and totals.get('credits') is not None:
        spent = (game.hiring['before'] or 0) - totals['credits']
        if spent >= game.hiring['cost'] * 0.9:
            game.say('    лидер «%s» нанят из запаса: казна убыла на %d'
                     % (game.hiring['name'], spent))
            game.wanted = None
        else:
            game.say('    лидера «%s» взять не удалось: казна не убыла (было %s, стало %s) '
                     '— обещание остаётся'
                     % (game.hiring['name'], game.hiring['before'], totals['credits']))
        save_state(game.taken, game.wanted)
        game.hiring = None
    if not names:
        game.say('    список колоний пуст — читать нечего')
        game.tap(COLONIES_RETURN, wait=1.2)
        return
    if builds or totals.get('hungry'):
        game.say('    колоний %d (%s), казна %s, еда %s'
                 % (len(names), ', '.join(name for name, _ in names),
                    totals.get('credits', '?'), totals.get('food', '?')))
    if not builds:
        if totals.get('hungry'):
            need = hunger_depth(totals)
            visit_colonies(game, book, names,
                           lambda one, who: feed_colony(one, who, need))
        elif (totals.get('food') or 0) >= FOOD_SURPLUS_TO_TRIM:
            visit_colonies(game, book, names, trim_farmers)
        game.tap(COLONIES_RETURN, wait=1.2)
        return
    # ХОЗЯЙСТВО ВЫКУПАЕТСЯ ПЕРВЫМ — правило нашего ИИ (`AiEmpireService.buyProject`):
    # сперва завод и лаборатория и на ВСЮ казну (они доход поднимают, значит берегут
    # резерв, а не проедают), и только если такой покупки нет — что угодно за половину.
    # Инструмент ходит по колониям по одной и цены заранее не знает, поэтому правило
    # выражено двумя заходами: сначала по списку покупаем только основание, а если ни
    # одна колония его не строит — возвращаемся к первой попавшейся со стройкой.
    bought = False
    spare = None
    # Грузовик закладывает ОДНА колония за заход — правило нашего ИИ: цель у них общая, и
    # без предела за грузовики взялись бы разом все свободные, а империя на несколько
    # ходов перестала бы строить что-либо ещё.
    freighter = False
    for name, spot in names:
        what, done = manage_one(game, book, name, spot, totals,
                                lambda project: not bought and any(
                                    rules.matches(project, base)
                                    for base in rules.FOUNDATION),
                                totals.get('want_freighters', False) and not freighter)
        bought = bought or done
        freighter = freighter or bool(what and rules.matches(what, rules.FREIGHTERS))
        if what and any(rules.matches(what, hull) for hull in rules.WARSHIPS):
            game.warships += 1
        if spare is None and what and not any(rules.matches(what, endless)
                                              for endless in rules.ENDLESS):
            spare = (name, spot, what)
        # Возврат с экрана колонии ведёт в список — но не мгновенно: окно выезжает, и
        # первый же взгляд застаёт ещё колонию. Поэтому смотрим несколько раз и нажимаем
        # «вернуться» повторно; вынесло куда-то ещё (объявление, вопрос) — остальные
        # колонии подождут следующего захода.
        for _attempt in range(3):
            where, _ = game.scene(book)
            if where == 'colonies':
                break
            if where == 'colony':
                game.tap(COLONY_RETURN, wait=1.4)
            else:
                return
        else:
            return
    if not bought and spare is not None:
        name, spot, what = spare
        game.tap(spot, wait=1.4)
        buy_project(game, book, what, totals.get('credits'))
        game.tap(COLONY_RETURN, wait=1.4)
    game.tap(COLONIES_RETURN, wait=1.4)


