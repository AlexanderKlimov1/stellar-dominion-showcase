FOUNDATION_KNOWN = {'Automated Factory', 'Research Lab'}

WORKERS_WHILE_WAITING = 1


def try_move(game, name, source, grows, before):
    """
    Переводит ОДНОГО жителя из ряда `source` в ряд `grows` — «взял и положил».

    ПРАВИЛО ИГРЫ, названное хозяином проекта 23.09.2026: нажатие левой кнопкой берёт всех,
    кто стоит ПРАВЕЕ точки нажатия (по крайнему правому — значит одного), дальше их несут
    курсором, а следующее нажатие кладёт их туда, где курсор стоит.

    Отсюда два следствия, на которых я подорвался, пока правила не знал:

    * берём за КРАЙНЮЮ ПРАВУЮ фигурку ряда — только так поднимается ровно один житель;
    * кладём на СВОБОДНОЕ место ряда-получателя. Нажатие по занятому месту — это не «положи
      сюда», а новое «возьми всех правее»: так прежний приём поднимал всех учёных, и они
      сваливались в рабочих следующим же нажатием. Ряды [4, 2, 2] превращались в [4, 4, 0],
      и объяснить это я не мог, пока не спросил.

    А раз неудачная попытка оставляет жителей НА КУРСОРЕ, после неё они кладутся обратно в
    свой ряд: брошенные на руках, они высыпались бы в первое попавшееся место следующим
    нажатием инструмента — это и портило колонии.

    Отдаёт новый счёт и способ, которым вышло; способ пуст — не вышло.
    """
    donor = before[source]
    if donor[1] <= 0:
        return before, None
    take = donor[2][-1]
    put = (JOB_FIRST_X + before[grows][1] * JOB_STEP, JOB_ROWS[grows][1])
    if put[0] > JOB_FIRST_X - 12 + JOB_ROW_WIDTH:
        game.say('    %s: в ряду «%s» места больше нет' % (name, JOB_ROWS[grows][0]))
        return before, None

    game.tap(take, wait=0.5)
    game.tap(put, wait=0.7)
    after = count_jobs(game.look())
    if after[grows][1] > before[grows][1]:
        return after, 'взял и положил'

    # Не вышло — значит, жители, скорее всего, остались на курсоре. Кладём их обратно на
    # свободное место СВОЕГО ряда: пустая попытка не должна стоить колонии.
    back = (JOB_FIRST_X + max(0, after[source][1]) * JOB_STEP, JOB_ROWS[source][1])
    game.tap(back, wait=0.7)
    after = count_jobs(game.look())
    return after, None


def push_research(game, name):
    """
    Переводит рабочих в учёные, пока ключевых построек ещё нет, — на старте наука важнее.

    ЗАЧЕМ. Пока завод и лаборатория не изучены, строить колонии нечего: всё, что она может
    заложить, — колониальная база, и та копится сама. Производство сверх одного рабочего в
    эти ходы почти ничего не решает, а те же жители в лаборатории приближают завод с
    лабораторией — то есть всё остальное развитие. Замерено партией 23.09.2026: империя
    доходила до завода к тридцатому ходу, держа в науке одного-двух жителей из шести.

    Фермеров НЕ ТРОГАЕМ: голод убивает жителей каждый ход, и еда идёт вперёд всего
    (`feed_colony`). Забираем только у станка и только сверх одного.
    """
    moved = 0
    for _attempt in range(8):
        counted = count_jobs(game.look())
        workers, scientists = counted[1], counted[2]
        if workers[1] <= WORKERS_WHILE_WAITING:
            break
        after, way = try_move(game, name, 1, 2, counted)
        if not way:
            game.say('    %s: перевести рабочего в науку не вышло ни одним способом '
                     '(было %s, стало %s)'
                     % (name, [job[1] for job in counted], [job[1] for job in after]))
            break
        moved += 1
    if moved:
        game.say('    %s: пока строить нечего — %d в науку, у станка остался %d'
                 % (name, moved, WORKERS_WHILE_WAITING))
    return moved


def leader_offer(game):
    """
    Предложение лидера: нанять сразу, а если денег нет — запомнить и вернуться потом.

    ПОЧЕМУ НЕ «ВСЕГДА НАНИМАТЬ». Прежде сцена жила таблицей и всегда жала HIRE. Когда
    казны не хватало, игра найма не делала, а инструмент шёл дальше как ни в чём не
    бывало — и лидер уходил в запас незамеченным. Между тем в MOO II отказ не уничтожает
    лидера: он ложится в Officer Pool окна LEADERS, и нанять его можно позже, когда казна
    позволит (решение хозяина проекта 23.09.2026).

    Что читаем: заголовок (имя и звание) и текст предложения, где стоит цена — «offers to
    join you for 600 BC now and 6 BC a turn». Первое число строки и есть цена найма.
    """
    image = game.look()
    title = ' '.join(line['text'] for line in text.read(image, LEADER_TITLE))
    offer = ' '.join(line['text'] for line in text.read(image, LEADER_OFFER))
    found = LEADER_COST.search(offer)
    cost = int(found.group(1)) if found else None
    worth = any(word.lower() in (title + ' ' + offer).lower() for word in LEADER_WORTH)
    credits = game.credits
    game.say('    лидер: «%s» за %s BC, казна %s, стоящий: %s'
             % (title or '?', cost, credits if credits is not None else '?',
                'да' if worth else 'нет'))
    # ТЕКСТ ПРЕДЛОЖЕНИЯ ПИШЕМ ЦЕЛИКОМ. По нему решаются обе вещи разом — цена найма и
    # «наш ли это лидер», — а читается он растровым шрифтом по словарю, в котором есть
    # пробелы: в партии 23.09.2026 имя вышло «Administrator ?rro? the lkarian Doctor», а
    # цена — «0 BC», хотя бесплатных лидеров не бывает. Решение, принятое по такому
    # тексту, — это решение вслепую, и, не видя его в журнале, я снова начну гадать.
    game.say('    текст предложения: «%s»' % offer)

    # НЕСТОЯЩЕГО НЕ БЕРЁМ, ДАЖЕ КОГДА ДЕНЬГИ ЕСТЬ. Сперва проверка «стоящий» решала только
    # случай нехватки казны, и выходила бессмыслица: инструмент называл лидера нестоящим и
    # тут же покупал его за 100 BC при казне 131 (партия 23.09.2026, ход 13). Анализ, после
    # которого всё равно покупаешь, — не анализ. А на старте это ещё и прямой ущерб: три
    # четверти казны уходят мимо рывка к заводу, ради которого жители и посажены в науку.
    if not worth:
        game.tap(LEADER_REJECT, wait=1.6)
        game.say('    не по нашей нужде — отказ')
        return
    if cost is None:
        # Цену не прочитали — значит, не знаем и того, по карману ли лидер. Нанимать
        # вслепую нельзя: именно так был нажат «нанять» при казне в два кредита. Отказ
        # лидера не уничтожает, он уходит в запас, и мы вернёмся, когда прочитаем цену.
        game.tap(LEADER_REJECT, wait=1.6)
        game.say('    цену прочитать не удалось — отказ, чтобы не нанимать вслепую')
        return
    if cost is not None and credits is not None and credits < cost:
        # Денег нет. Отказ — это не «навсегда нет»: лидер уходит в запас, и мы вернёмся.
        game.tap(LEADER_REJECT, wait=1.6)
        game.wanted = {'name': title, 'cost': cost}
        save_state(game.taken, game.wanted)
        game.say('    казны не хватает — запомнили и вернёмся, когда будет %d BC' % cost)
        return
    game.tap(LEADER_HIRE, wait=1.8)
    game.say('    нанят')


def hire_remembered(game, book):
    """
    Возвращается в окно LEADERS и нанимает лидера, которого запомнили без денег.

    Кого именно брать, в запасе не выбирается чтением: имена в списке мелкие, а мест
    всего три. Поэтому пробуем места по порядку и смотрим на казну: убыла — значит наняли.
    Грубо, зато не врёт — казна это единственное, что здесь можно проверить наверняка.
    """
    want = game.wanted
    game.say('    возвращаемся за лидером «%s» за %d BC (казна %s)'
             % (want['name'], want['cost'], game.credits))
    # ОДНО МЕСТО ЗАПАСА ЗА ПОПЫТКУ. Сперва здесь перебирались все три подряд с нажатием
    # HIRE у каждого — и это наняло ДВОИХ разом: казна убыла на 355 при цене лидера 180
    # (партия 24.09.2026). Кого именно берут, в запасе прочитать нечем (имена там мелкие),
    # поэтому пробуем по одному и помним, какое место уже пробовали: не тот — следующая
    # попытка возьмёт соседнее. Так ошибка стоит одного лидера, а не всей казны.
    slot = want.get('slot', 0) % len(LEADERS_POOL_SLOTS)
    game.tap(MAP_LEADERS, wait=1.8)
    game.tap(LEADERS_POOL, wait=1.2)
    game.tap(LEADERS_POOL_SLOTS[slot], wait=0.8)
    game.tap(LEADERS_HIRE, wait=1.6)
    where, _ = game.scene(book)
    if where in ('leaders', None):
        game.tap(LEADERS_RETURN, wait=1.6)
    want['slot'] = slot + 1
    # НАЁМ ПОДТВЕРЖДАЕТ КАЗНА, А НЕ НАШЕ НАЖАТИЕ. Сперва здесь стояло «нажали и забыли»:
    # обещание стиралось сразу, и лидер, которого не взяли (место занято, окно открылось не
    # то, нажатие ушло мимо), терялся молча. Проверить нам нечем, кроме денег, — поэтому
    # запоминаем, сколько было, а сверит это следующий же разбор списка колоний.
    game.hiring = {'name': want['name'], 'cost': want['cost'], 'before': game.credits}
    game.wanted = want
    save_state(game.taken, game.wanted)


