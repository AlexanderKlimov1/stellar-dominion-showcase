def research_blocks(game, image):
    """Что предлагает экран исследований: по разделу его цена и строки технологий."""
    blocks = {}
    for row, y in enumerate(RESEARCH_ROWS):
        for column in (0, 1):
            cost = None
            for line in text.read(image, (RESEARCH_COST_X[column], y, 60, 14),
                                  fits=text.green):
                cost = cost if cost is not None else number(line['text'])
            lines = []
            box = (RESEARCH_BLOCK_X[column], y + 16,
                   RESEARCH_BLOCK_WIDTH, RESEARCH_BLOCK_HEIGHT)
            for line in text.read(image, box, fits=text.green):
                if not line['text']:
                    continue
                left, top, width, height = line['box']
                lines.append((line['text'],
                              (left + min(width, 60) // 2, top + height // 2)))
            blocks[(row, column)] = {'cost': cost, 'lines': lines}
    return blocks


def choose_research(game):
    """
    Выбирает, что исследовать, по нужде — `ResearchService.autoChoose` нашего сервера.

    Прежде здесь стояло постоянное нажатие по одной и той же клетке, потом «самое
    дешёвое», и ни то ни другое не довело империю ни до завода, ни до лаборатории:
    дешёвое ведёт куда попало, а постоянное — туда, где на этом месте оказался раздел за
    810 очков (сто четыре хода при девяти очках науки в ход).
    """
    image = game.look()
    blocks = research_blocks(game, image)
    # Что показал экран — в журнал целиком: выбор науки решается тем, ЧТО в блоке
    # написано, и разбирать потом «почему взяли не то» без этой строки нечем.
    game.say('    разделы: %s' % '; '.join(
        '%s %s' % (block['lines'][0][0] if block['lines'] else '—', block['cost'])
        for _place, block in sorted(blocks.items())))
    spot, why, closed = rules.choose_field(blocks, game.taken)
    if spot is None:
        game.say('    %s' % why)
        return
    if closed:
        game.taken.add(closed)
        save_state(game.taken, game.wanted)
    game.say('    исследуем: %s (закрыто: %s)'
             % (why, ', '.join(sorted(game.taken)) or 'ничего'))
    game.tap(spot, wait=2.5)


