def dismiss(game, before):
    """
    Пробует закрыть незнакомую сцену — Esc, потом нажатием по середине.

    Зачем вообще пробовать, а не останавливаться сразу, как делает обход сцен. Половина
    незнакомых сцен MOO II — это ОБЪЯВЛЕНИЯ: «Colony built on Sol Prime», находка, весть
    от посла. Картинка у каждого своя (поверхность именно этой планеты), и приметой их не
    исчерпать никогда: партия вставала бы каждые десять ходов.

    Оправдание вслепую тут одно, и оно узкое: Esc и нажатие по пустому месту в MOO II
    ничего не решают и ничего не тратят — ими закрывают, а не выбирают. Всё, что ВЫБИРАЕТ
    (что построить, что изучать, куда сесть), названо сценой и решается чтением. Снимок
    незнакомой сцены при этом сохраняется всегда.
    """
    sign = probe.signature(before)
    for attempt in range(3):
        if attempt == 0:
            probe.press('ESCAPE')
        else:
            probe.click(game.hwnd, 320, 240)
        time.sleep(1.4)
        after, _ = probe.settle(game.hwnd)
        if probe.distance(probe.signature(after), sign) > probe.SAME_SCENE:
            return True
    return False


def play(game, book, turns, save_once=False, load_once=False, save_at=0):
    """Ход за ходом: сцену узнали, нужное сделали, остальное — по таблице сцен."""
    turn = 0
    for step in range(1, turns * 6 + 1):
        name, image = game.scene(book)
        # Сцена, снятая самой собой и ещё не названная, — такая же незнакомая: действий у
        # неё нет, и стоять на ней нечего.
        if name is not None and name.startswith('unknown-'):
            name = None
        if name is None:
            found, path = probe.remember(book, image)
            game.say('%03d. НОВАЯ СЦЕНА %s — снимок %s' % (step, found['name'], path))
            if not dismiss(game, image):
                game.say('    незнакомая сцена не закрывается — дальше идти вслепую нельзя')
                break
            continue
        if load_once and name == 'galaxy-map':
            load_once = False
            load_game(game)
            continue
        if save_once and name == 'galaxy-map':
            save_once = False
            save_game(game)
            continue
        if name == 'research-select':
            game.say('%03d. выбор исследования' % step)
            choose_research(game)
            continue
        # ЛИДЕР РЕШАЕТСЯ КОДОМ, А НЕ ТАБЛИЦЕЙ СЦЕН. В таблице у этой сцены стояло одно
        # действие — «жать HIRE», — и при нехватке казны найм молча не случался, а лидер
        # уходил в запас незамеченным.
        if name == 'leader-offer':
            game.say('%03d. лидер предлагает службу' % step)
            leader_offer(game)
            continue
        if name == 'colony-base-target':
            game.say('%03d. готова колониальная база — выбираем планету' % step)
            place_colony_base(game, book)
            continue
        if name == 'galaxy-map':
            turn += 1
            game.say('%03d. ход %d' % (step, turn))
            if turn % BUILD_EVERY == 1:
                manage_colonies(game, book)
                continue
            if turn > turns:
                break
            # СОХРАНЯЕМСЯ НА НАЗНАЧЕННОМ ХОДУ. Смысл в том, чтобы следующая проба нового
            # управления начиналась ОТСЮДА, а не с сотворения галактики: до кораблей партия
            # идёт полчаса, и за вечер на этом сгорело пять прогонов подряд.
            if save_at and turn >= save_at:
                save_at = 0
                save_game(game)
                continue
            # ЕДА КАЖДЫЙ ХОД, стройка — раз в несколько. Голод в MOO II уносит жителя
            # каждый ход, а колонии осматривались только на ходах 1, 6, 11…: между ними
            # империя голодала без присмотра, и это и была та самая «колония голодает с
            # первых ходов». Заход с `builds=False` дешёвый — открыть список, прочитать
            # сводку и уйти; внутрь колоний он лезет, только если империя голодает.
            if turn % SEND_EVERY == 0:
                send_fleets(game, book, image)
                where, image = game.scene(book)
                if where != 'galaxy-map':
                    continue
            manage_colonies(game, book, builds=False)
            # Казна только что перечитана — самое время вернуться за лидером, если такой
            # обещан. Проверка стоит здесь, а не при самом предложении, потому что деньги
            # копятся ходами, а обещание ждать умеет.
            if (game.wanted and game.credits is not None
                    and game.credits >= game.wanted.get('cost', 0)):
                hire_remembered(game, book)
            # Нажимать «конец хода» вслепую нельзя: пока мы ходили по колониям, могло
            # всплыть объявление, и нажатие ушло бы в него. Не на карте — пусть разбирает
            # следующий круг, он для того и устроен.
            where, _ = game.scene(book)
            if where != 'galaxy-map':
                continue
            game.tap(MAP_TURN, wait=2.0)
            continue
        scene = next(one for one in book['scenes'] if one['name'] == name)
        actions = scene.get('actions') or []
        if not actions:
            game.say('%03d. %s: действий нет — дальше идти нечем' % (step, name))
            break
        game.say('%03d. %s' % (step, name))
        for action in actions:
            probe.do_action(game.hwnd, action)
    return turn


def main():
    parser = argparse.ArgumentParser(description='Игра в оригинал MOO2 за человека')
    parser.add_argument('--turns', type=int, default=30, help='сколько ходов сыграть')
    parser.add_argument('--no-launch', action='store_true')
    parser.add_argument('--save', action='store_true',
                        help='сохранить партию, дойдя до карты, и играть дальше')
    parser.add_argument('--save-at', type=int, default=0,
                        help='сохранить на этом ходу: до кораблей игра идёт полчаса, и '
                             'пробовать новое управление надо с готовой партии, а не с нуля')
    parser.add_argument('--load', action='store_true',
                        help='поднять свою ячейку вместо новой партии')
    parser.add_argument('--fresh', action='store_true',
                        help='новая партия: забыть, какие нужды были закрыты')
    args = parser.parse_args()

    if args.fresh and os.path.exists(STATE):
        os.remove(STATE)
    if args.no_launch:
        hwnd, title = probe.find_window()
        if not hwnd:
            raise SystemExit('игра не запущена, а поднимать её запретили')
    else:
        hwnd, title = probe.launch()
    game = Game(hwnd)
    game.say('окно игры: %s' % title)
    book = probe.read_scenes()
    played = play(game, book, args.turns,
                  save_once=args.save, load_once=args.load, save_at=args.save_at)
    game.say('сыграно ходов: %d' % played)
    with open(REPORT, 'w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(game.log) + '\n')
    print('отчёт: %s' % REPORT)


if __name__ == '__main__':
    main()
