def number(line):
    """Первое целое число строки; пусто — числа в ней нет."""
    digits = ''
    for sign in line:
        if sign.isdigit():
            digits += sign
        elif digits:
            break
    return int(digits) if digits else None


def signed_number(line):
    """
    Первое целое строки ВМЕСТЕ СО ЗНАКОМ; пусто — числа в ней нет.

    Отдельно от `number` нарочно. Обычное чтение знака не знает, и это правильно везде,
    где минус в строке — не минус числа, а дефис: в списке стройки и в вопросе о выкупе
    («Colony Base - 60») знак утащил бы цену в отрицательные. А вот еда империи бывает
    отрицательной по-настоящему, и без знака голод в −3 читался как «еда 3»: в журнале
    стояло бодрое «еда 1» ровно в тот ход, когда колония умирала с голоду.
    """
    digits = ''
    minus = False
    for position, sign in enumerate(line):
        if sign.isdigit():
            if not digits and position and line[position - 1] == '-':
                minus = True
            digits += sign
        elif digits:
            break
    if not digits:
        return None
    return -int(digits) if minus else int(digits)


def load_state():
    """Закрытые нужды текущей партии; нет файла — партия начата с чистого листа."""
    if not os.path.exists(STATE):
        return set(), None
    try:
        with io.open(STATE, encoding='utf-8') as file:
            saved = json.load(file)
            return set(saved.get('taken', [])), saved.get('wanted')
    except (ValueError, OSError):
        # Битый файл памяти — не повод не играть: начнём помнить заново.
        return set(), None


def save_state(taken, wanted=None):
    """
    Кладёт память партии на диск: следующий запуск продолжит ту же партию.

    Лидер, за которым обещано вернуться, лежит здесь же по той же причине, что и нужды
    науки: партия играется несколькими запусками, и обещание обязано их пережить — иначе
    оно значит ровно столько, сколько длится один запуск.
    """
    tmp = STATE + '.tmp'
    with io.open(tmp, 'w', encoding='utf-8', newline='\n') as file:
        json.dump({'taken': sorted(taken), 'wanted': wanted}, file,
                  ensure_ascii=False, indent=1)
    os.replace(tmp, STATE)


