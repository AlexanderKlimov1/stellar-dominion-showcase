#: Пороги яркости, какими пробуется очередь стройки, в порядке предпочтения.
#:
#: Зачем их несколько. Общий порог (150) прихватывает в очереди тусклую рябь, и она идёт в
#: счёт наравне с буквами: на снимке `colony-build.png` строка «Trade Goods» читалась как
#: «Trade Goods» плюс лишняя «?», а в живой партии первая строка выходила «?» и «?? ?» —
#: то есть колония выглядела занятой неизвестной стройкой, и её не трогали вовсе. Замерено
#: по тому же снимку: на 170 и выше строка читается начисто, на 130 и ниже рассыпается.
#: Поэтому порог не назначен числом, а ВЫБИРАЕТСЯ: побеждает тот, на котором непрочитанных
#: букв меньше. Так строка, которая видна только тусклой, всё равно не потеряется.
QUEUE_BRIGHTS = (170, 150, 190)


def queue_rows(game, image):
    """
    Строки очереди колонии — самым удачным порогом яркости.

    Заголовок «Build List for ...» выбрасывается: это подпись окна, а не проект.
    """
    best_rows, best_score = [], None
    for bright in QUEUE_BRIGHTS:
        rows = [row for row in game.rows(image, BUILD_QUEUE, bright=bright)
                if not rules.matches(row[0], 'Build List')]
        # Сперва меньше непрочитанных букв, при равенстве — больше строк: потерять строку
        # опаснее, чем прочитать её с огрехом.
        score = (sum(row[0].count('?') for row in rows), -len(rows))
        if best_score is None or score < best_score:
            best_rows, best_score = rows, score
    return best_rows


def clear_queue(game):
    """
    Чистит очередь колонии: строка убирается ДВУМЯ нажатиями.

    Зачем вообще чистить. Нажатие по строке столбца не назначает стройку, а ДОПИСЫВАЕТ её
    в очередь — это видно на экране: «Build List for Sol V» с нашими строками подряд. А
    первой в очереди у колонии стоят «Trade Goods», которые не кончаются никогда, — и всё,
    что дописано следом, ждёт вечно. Те же грабли, что у нас описаны правилом «бесконечная
    стройка стапеля не держит»: у оригинала она держит, и потому очередь приходится
    открывать самому.

    Убирается строка не одним нажатием, а двумя: первое пишет в ней «delete Trade Goods» и
    обводит красным, второе исполняет.
    """
    # ЦИКЛ ПРОВЕРЯЕТ, УБЫВАЕТ ЛИ ОЧЕРЕДЬ. Прежде он просто повторял пару нажатий двенадцать
    # раз, и строка, которая не удаляется, стоила двадцати четырёх пустых нажатий подряд —
    # по полминуты на колонию и град кликов по чужим местам окна. Теперь после каждой пары
    # очередь пересчитывается: стало не короче — значит, эта строка не убирается, и дальше
    # долбить её незачем. То же правило, что у сторожа балансового круга: «не вышло» и
    # «сделано» — разные исходы, и путать их нельзя.
    was = None
    for _ in range(12):
        rows = queue_rows(game, game.look())
        if not rows:
            return True
        if was is not None and len(rows) >= was:
            game.say('    очередь не убывает на «%s» — больше не нажимаем' % rows[0][0])
            return False
        if not is_colony_name(rows[0][0]):
            # СТРОКУ, КОТОРУЮ НЕ ПРОЧЛИ, НЕ ТРОГАЕМ. Нечитаемая строка очереди («??») за
            # партию встречалась десятки раз, и каждый раз стоила двух нажатий впустую:
            # убрать её не удавалось ни разу. Что это такое, достоверно неизвестно — скорее
            # всего, ТЕКУЩАЯ стройка, которую из очереди удалить нельзя в принципе, её
            # меняют выбором в списке. Пока это догадка, и поведение выбрано по ней
            # осторожное: не жать. Проверять догадку надо снимком окна стройки в этот миг.
            game.say('    первая строка очереди не читается («%s») — не трогаем её'
                     % rows[0][0])
            return False
        was = len(rows)
        spot = rows[0][1]
        game.tap(spot, wait=0.5)
        game.tap(spot, wait=0.5)
    return False


def empire_totals(game, image):
    """
    Сводка империи из списка колоний: казна и еда.

    Ради двух чисел: по казне считается выкуп (наш ИИ кладёт на хозяйство всю казну, на
    прочее половину), по еде — голодает ли империя, а голод в нашем ИИ идёт вперёд всего
    остального и мимо тормоза по содержанию.
    """
    totals = {}
    for line in text.read(image, COLONIES_TOTALS, bright=COLONIES_BRIGHT):
        said = line['text']
        if rules.matches(said, 'Reserve'):
            totals['credits'] = number(said)
        elif rules.matches(said, 'Food'):
            # СО ЗНАКОМ: по величине нехватки считается, СКОЛЬКО жителей переводить на еду.
            # Пока читали без знака, «еда −3» и «еда 3» выглядели одинаково, и голод
            # лечился одним жителем при любой глубине ямы.
            totals['food'] = signed_number(said)
            totals['hungry'] = '-' in said
        elif rules.matches(said, 'Freighters'):
            # Минус в этой строке и значит «грузовиков не хватает»: игра пишет ПОТРЕБНОСТЬ
            # сверх имеющегося (у нас было «Freighters: -3»). Числа мало — важен знак.
            totals['want_freighters'] = '-' in said
    return totals


