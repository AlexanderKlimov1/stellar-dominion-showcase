def _english(value):
    return value.get('en') if isinstance(value, dict) else value


def levels_by_field():
    """Названия уровней каждого раздела по порядку — из нашего `tech.json`."""
    with io.open(TECH_FILE, encoding='utf-8') as file:
        tree = json.load(file)
    return {key: [_english(level['level_name']) for level in category['levels']]
            for key, category in tree['tech_categories'].items()}


def recommended_names():
    """
    Имена технологий, отмеченных в нашем дереве как `recommended`.

    Это то же, чем пользуется `ResearchService.pickOption`: обычная раса берёт на уровне
    отмеченную технологию, а не случайную. Инструменту это нужно затем же — когда в уровне
    нет нужного, выбрать из него надо ЛУЧШЕЕ, а не первое попавшееся.
    """
    with io.open(TECH_FILE, encoding='utf-8') as file:
        tree = json.load(file)
    names = set()
    for category in tree['tech_categories'].values():
        for level in category['levels']:
            codes = set(level.get('recommended') or ())
            for tech in level['technologies']:
                if tech['code'] in codes:
                    names.add(_english(tech['name']))
    return names


