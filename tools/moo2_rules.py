#: Буквы, у которых в шрифте игры ОДИН силуэт, и различить их чтением нельзя в принципе.
#: Заглавная «I» и строчная «l» нарисованы одной и той же чертой — словарь честно сказал
#: об этом при учении («силуэт уже выучен как l, а теперь I»), и «Artificial Intelligence»
