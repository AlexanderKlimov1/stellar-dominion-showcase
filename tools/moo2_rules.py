#: пройденный уровень Computers и вела раздел к лаборатории, которая уже была изучена.
SAME_SHAPE = {'i': 'l'}


def _fold(letter):
    return SAME_SHAPE.get(letter, letter)


def matches(seen, wanted):
    """
    Совпало ли прочитанное с задуманным.

    Незнакомая буква приходит из чтения знаком «?» и считается СОВПАВШЕЙ с любой: словарь
    шрифта пополняется по ходу дела, и ждать полного алфавита, чтобы начать играть, было
    бы глупо. Ошибиться этим нельзя всерьёз — длина и все знакомые буквы обязаны совпасть.

    Сравнение идёт ПО НАЧАЛУ строки: в списке стройки за именем стоит срок («Colony Base –
    34t»), а имена вещей у MOO II не бывают началом друг друга.
    """
    seen = (seen or '').strip()
    if len(seen) < len(wanted):
        return False
    for left, right in zip(seen[:len(wanted)], wanted):
        if left != '?' and _fold(left.lower()) != _fold(right.lower()):
            return False
    return True


def first(order, offered):
    """
    Первое из списка, что есть в предложенном, — `AiEmpireService.first`.

    `offered` — строки экрана: пары «что написано, куда нажимать».
    """
    for wanted in order:
        for seen, spot in offered:
            if matches(seen, wanted):
                return wanted, spot
    return None, None


def choose_project(offered, hungry=False, want_freighters=False, want_warship=False,
                   foundation_pending=False):
    """
    Что строить этой колонии — цепочка `AiEmpireService.choose`, её переносимая часть.

    Порядок замысла (решение хозяина проекта 23.09.2026): еда вперёд всего, следом
    грузовики, потом ОСНОВАНИЕ — завод и лаборатория на родном мире, потом РАЗВЕДЧИК,
    потом максимум колониальных баз в своей системе, потом колониальный корабль к лучшей
    из разведанных систем, потом развитие, и только в самом низу — дома и товары.

    От `AiEmpireService.choose` это отличается одним звеном: там колониальная база стоит
    раньше первого боевого корабля. Почему переставлено — сказано у самой ветки.

    `foundation_pending` — завод или лаборатория ещё не изучены. Выбор он БОЛЬШЕ НЕ МЕНЯЕТ
    и остался ради одного: по нему `moo2_play` понимает, что колонии ещё предстоит смена
    очереди на завод. Раньше этот признак запирал колониальную базу, и колония ждала
    завода на домах; почему запрет снят — сказано у самой ветки базы.

    Ветки войны, тревоги и границы пропущены:
    инструмент не читает признака войны (точка расширения названа в шапке файла).

    Грузовик стоит рядом с едой и у нас, и по той же причине: это та же еда, только
    чужая — без грузового флота излишек кормовых миров некуда девать, и каждая колония
    вынуждена кормиться сама.

    Дома стоят внизу не по вкусу, а по дважды выученному в нашем проекте уроку: стройка
    бесконечная, и поставленная выше завода она занимает колонию навсегда.
    """
    if hungry:
        found, spot = first(FOOD, offered)
        if found:
            return found, spot, 'еда: империя голодает'

    if want_freighters:
        found, spot = first([FREIGHTERS], offered)
        if found:
            return found, spot, 'грузовиков не хватает'

    found, spot = first(FOUNDATION, offered)
    if found:
        return found, spot, 'основание: завод и лаборатория раньше расселения'

    # РАЗВЕДЧИК ВЫШЕ КОЛОНИАЛЬНОЙ БАЗЫ, и это НАМЕРЕННЫЙ отход от `AiEmpireService.choose`,
    # где база стоит раньше первого боевого корабля.
    #
    # Причина в разнице положений, а не в несогласии с нашим ИИ. Наш ИИ ЗНАЕТ КАРТУ ЦЕЛИКОМ
    # с первого хода (так в MOO II и устроен ИИ), и разведка ему не нужна вовсе — корабль у
    # него первым делом гарнизон, а не глаза. Инструмент же играет за ЧЕЛОВЕКА: карта
    # закрыта, и пока разведчик не слетал, селиться некуда и торговать не с кем.
    #
    # Что бывает без этой перестановки, измерено партией 23.09.2026: колониальная база в
    # MOO II доступна, пока в системе осталась хоть одна свободная планета, поэтому очередь
    # до разведчика не доходила НИКОГДА. За всю партию империя построила семь баз и один
    # грузовик — ни разведчика, ни колониального корабля, ни завода.
    if want_warship:
        found, spot = first(WARSHIPS, offered)
        if found:
            return found, spot, 'разведчик: без него расселение слепо'

    # КОЛОНИАЛЬНАЯ БАЗА СТРОИТСЯ И ДО ЗАВОДА (решение хозяина проекта 23.09.2026).
    #
    # Прежде она была заперта `foundation_pending`: база стоит 200 единиц и строится
    # тридцать с лишним ходов, завод приходит ходов через двенадцать, — и казалось, что
    # колония встретит его занятой. Довод отменён тем, что ВЛОЖЕННОЕ В СТРОЙКУ НЕ
    # ПРОПАДАЕТ: накопленные единицы производства остаются у колонии, и сменив очередь на
    # завод, она отдаёт их заводу. То есть эти двенадцать ходов колония не ждёт, а копит.
    #
    # А вот чем она была занята взамен — домами, — это и оказалось настоящей потерей: дома
    # растят вместимость, которой некуда расти, и колония тратила ходы впустую. Смену
    # очереди на завод делает `moo2_play.manage_one`, когда завод появляется в списке.
    found, spot = first([COLONY_BASE], offered)
    if found:
        return found, spot, 'расселение внутри своей системы'

    found, spot = first([COLONY_SHIP, OUTPOST_SHIP], offered)
    if found:
        return found, spot, 'расселение к чужим звёздам'

    found, spot = first(DEVELOPMENT, offered)
    if found:
        return found, spot, 'развитие по окупаемости'

    found, spot = first([HOUSING], offered)
    if found:
        return found, spot, 'расти некуда больше — дома'

    found, spot = first([TRADE_GOODS], offered)
    if found:
        return found, spot, 'строить нечего — товары'
    return None, None, 'в списке нет ничего из замысла'


