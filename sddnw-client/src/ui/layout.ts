/**
 * Размеры панелей, которые карта учитывает при раскладке окна галактики.
 *
 * Панели лежат поверх канваса, поэтому сцена Phaser должна знать, сколько места они
 * занимают. Держим числа здесь, чтобы разметка панелей и окно карты не разъезжались.
 *
 * **Отдаются они строками в `rem`, а не числами**, и это главное здесь правило: размер
 * текста игрок меняет настройкой ({@link textScaleFactor}), а `rem` считается от корневого
 * кегля — значит, панели растут вместе с надписями, которые в них лежат. Пиксель такого
 * не умеет: при крупном тексте прежняя полоса меню обрезала бы собственные подписи.
 *
 * Базовые числа — пиксели при масштабе 100 %.
 */
import { textScaleFactor } from './textScale';

/** Пиксели при стократном масштабе → доля корневого кегля. */
const rem = (px: number): string => `${px / 16}rem`;

/**
 * Кегль надписей нижнего меню.
 *
 * Вдвое крупнее прежнего (11): на большом экране надписи меню читались с трудом, а это
 * единственные подписи, которыми игра управляется постоянно. Держим здесь, а не классами
 * по месту: высота полосы и кегль связаны, и разъезжаться им незачем.
 *
 * <b>Верхней полосы у карты больше нет</b>: меню «Игра» переехало в нижнюю, а весь верх
 * экрана отдан галактике — оттого и размеров у неё здесь не осталось.
 */
export const HUD_FONT_SIZE = rem(22);

/** Высота кнопки хода и кегль её надписи — тоже вдвое против прежних 30 и 12. */
export const TURN_BUTTON_HEIGHT = rem(60);
export const TURN_BUTTON_FONT_SIZE = rem(24);
/** Высота картинки-рамки на кнопке хода: вдвое против прежних 22. */
export const TURN_BUTTON_IMAGE_HEIGHT = rem(44);

/**
 * Кегль слова на кнопке хода.
 *
 * Меньше кегля самой кнопки: слово лежит ВНУТРИ нарисованной рамки, а номер хода — рядом
 * с ней, на свободном месте. Раньше слова тут не было вовсе — оно было нарисовано в
 * пикселях картинки и потому не переводилось (см. SidePanel).
 */
export const TURN_BUTTON_LABEL_FONT_SIZE = rem(20);

/**
 * Ширина правой панели состояния — SidePanel. Она занимает всю высоту экрана.
 *
 * Зазора между картой и панелью нет намеренно: он был чёрной полосой вдоль всей высоты
 * экрана, а в оригинале окно галактики примыкает к соседним панелям вплотную.
 */
export const SIDE_PANEL_WIDTH_PX = 384;
export const SIDE_PANEL_WIDTH = rem(SIDE_PANEL_WIDTH_PX);

/**
 * Та же ширина, но В ПИКСЕЛЯХ И ПО НЫНЕШНЕМУ МАСШТАБУ — для карты галактики.
 *
 * Канвас Phaser считает своё окно пикселями и о `rem` не знает вовсе, поэтому ширину ему
 * приходится досчитывать самим. Функция, а не число: масштаб меняется в игре, и
 * запомненное при загрузке значение оставило бы карту под панелью.
 */
export const sidePanelWidthPx = (): number => SIDE_PANEL_WIDTH_PX * textScaleFactor();

/**
 * Атрибут, которым в разметке подписаны панели поверх карты: сцена снимает с них границы
 * и сжимает область камеры до полосы между ними. Панелей сверху может быть несколько
 * (меню и HUD), поэтому берётся не высота панели, а её дальний от края экрана край.
 *
 * Здесь, а не в сцене: по той же метке окно «флот в пути» узнаёт, где кончается карта.
 */
export const MAP_INSET_ATTRIBUTE = 'data-map-inset';

/**
 * Высота крайних сегментов правой панели: галактический год сверху и ход снизу.
 *
 * Выросла вместе с кеглем панели (30.09.2026): надписи в ней стали вдвое крупнее, и в
 * прежние тридцать пикселей строка перестала помещаться — она вылезала за линию сегмента.
 */
export const SIDE_PANEL_EDGE_HEIGHT = rem(46);
