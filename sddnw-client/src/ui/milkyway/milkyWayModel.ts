/**
 * Слои луча: дымка, сам луч и ядро — один в другом.
 *
 * Слоями луч и получает мягкий край: каждый прозрачен, и вместе они складываются светом.
 * У каждого своя длина (оболочка достаёт дальше гамма-доли), своя толщина и своё зерно
 * ряби — иначе слои рябили бы в лад, и вся неровность свернулась бы в одну ровную форму.
 */
export interface JetLayer {
  /** По ключу экран берёт градиент и срок дыхания слоя. */
  code: 'haze' | 'beam' | 'core';
  /** Во сколько раз слой шире основного профиля. */
  girth: number;
  heightLy: number;
  /** Зерно ряби: сдвиг синусов, свой у каждого слоя. */
  seed: number;
}

export const JET_LAYERS: JetLayer[] = [
  { code: 'haze', girth: 1.35, heightLy: JET_REACH_LY, seed: 0.7 },
  { code: 'beam', girth: 0.85, heightLy: JET_REACH_LY * 0.88, seed: 2.9 },
  { code: 'core', girth: 0.3, heightLy: FERMI_HEIGHT_LY * 1.2, seed: 5.1 },
];

/**
 * Рябь края луча: два несоизмеримых синуса от высоты.
 *
 * Несоизмеримых нарочно — у суммы таких синусов нет короткого периода, и край не
 * повторяет сам себя по высоте. Случайного разброса здесь быть не может: силуэт
 * пересчитывается на каждом кадре вращения, и {@code Math.random} перетряхивал бы луч
 * шестьдесят раз в секунду.
 */
const ripple = (part: number, seed: number): number =>
  1 + 0.19 * Math.sin(part * 7.7 + seed) + 0.11 * Math.sin(part * 16.3 + seed * 1.7);

/**
 * Сама доля излучения — силуэтом, а не кольцами.
 *
 * Кольцами доля читалась чертежом: пять окружностей одна над другой, между ними пусто, и
 * при повороте они складывались в решётку. Луч же — это то, чем выброс и выглядит:
 * прозрачное синее свечение, расходящееся от центра вдоль оси вращения и гаснущее к
 * вершине.
 *
 * <b>Профиль:</b> узкое основание у самой дыры, раздутая доля посередине и ненулевой
 * хвост на вершине. Хвост важен: прежний профиль сходился в точку, и удлинённый до
 * оболочки луч читался иглой, а у выброса вершина открыта — он уходит за край видимого,
 * а не заканчивается острием.
 *
 * <b>Неровность</b> у луча двойная и вся считанная ({@link ripple}): рябит его край по
 * высоте, и у двух краёв рябь своя — силуэт не совпадает сам с собой ни по высоте, ни
 * между краями. К вершине ось ещё и слегка ведёт в сторону. Северная доля крупнее южной,
 * как на снимках: выброс шёл в неоднородную среду, и ровных половин у него нет.
 *
 * Возвращается готовая строка точек многоугольника: вверх по одному краю, вниз по
 * другому. Ширина берётся из проекции — с ребра луч узкий и длинный, плашмя он смотрит
 * на наблюдателя и становится пятном вокруг центра, как и положено выбросу, глядящему в
 * глаза.
 *
 * @param side  +1 — доля над диском, −1 — под ним
 * @param layer слой луча: длина, толщина и зерно ряби — {@link JET_LAYERS}
 */
export const jetOutline = (
  side: number,
  view: ViewAngles,
  width: number,
  height: number,
  layer: JetLayer,
  // Восемнадцати ступеней силуэту хватает: рябь плавная, и лишние точки видны не глазу, а
  // только кадру — каждая из них это ещё одна пара чисел в разметке на каждом повороте.
  steps = 18,
): string => {
  const basis = viewBasis(view, width, height);
  const left: string[] = [];
  const right: string[] = [];
  const skew = side > 0 ? 1.06 : 0.92;
  const reach = layer.heightLy * skew;

  for (let index = 0; index <= steps; index += 1) {
    const part = index / steps;
    const swell = 0.09 + 0.91 * Math.sin(Math.PI * Math.pow(part, 0.72));
    const lobe = FERMI_MAX_RADIUS_LY * swell * layer.girth * skew;
    const z = side * reach * part;
    // Ось луча к вершине уводит в сторону — на доли её собственной толщины.
    const lean = FERMI_MAX_RADIUS_LY * 0.16 * Math.pow(part, 1.7)
      * Math.sin(part * 2.1 + layer.seed);
    const axis = toScreenWith({ x: lean, y: lean * 0.6, z }, basis);
    // Поперечник луча берём по двум точкам его окружности ВОКРУГ ОСИ ВРАЩЕНИЯ: она лежит
    // в плоскости диска, поэтому её проекция и даёт настоящую ширину при любом наклоне.
    // Мерится она от несмещённой середины — увод оси ширину менять не должен.
    const center = toScreenWith({ x: 0, y: 0, z }, basis);
    const edgeA = toScreenWith({ x: lobe, y: 0, z }, basis);
    const edgeB = toScreenWith({ x: 0, y: lobe, z }, basis);
    const half = Math.max(
      Math.hypot(edgeA.x - center.x, edgeA.y - center.y),
      Math.hypot(edgeB.x - center.x, edgeB.y - center.y),
    );

    // Направление луча на экране — от центра к этой точке оси; у самого центра его ещё
    // нет, и тогда край откладывается по горизонтали.
    const dx = axis.x - basis.halfX;
    const dy = axis.y - basis.halfY;
    const length = Math.hypot(dx, dy) || 1;
    const nx = -dy / length;
    const ny = dx / length;
    const halfLeft = half * ripple(part, layer.seed);
    const halfRight = half * ripple(part, layer.seed + 3.4);

    left.push(`${(axis.x + nx * halfLeft).toFixed(1)},${(axis.y + ny * halfLeft).toFixed(1)}`);
    right.unshift(
      `${(axis.x - nx * halfRight).toFixed(1)},${(axis.y - ny * halfRight).toFixed(1)}`,
    );
  }
  return [...left, ...right].join(' ');
};

/**
 * Аккреционный диск: кольца вещества у самой дыры, <b>в плоскости её вращения</b>.
 *
 * Радиусы — в единицах ПОЛЯ, а не в световых годах, и это единственное место схемы, где
 * так. Настоящий диск Sgr A* размером в световые часы: в масштабе Галактики это меньше
 * точки, и привязка к световым годам оставляла бы выбор между невидимой чертой и диском
 * величиной с ядро. Диск поэтому нарисован увеличенным — ровно как и сама дыра, чья точка
 * тоже взята в одиннадцать единиц вместо нуля.
 *
 * Плоскость при этом настоящая: кольцо строится {@link accretionRing} по тем же поворотам,
 * что и всё остальное, поэтому при наклоне сцены оно сплющивается вместе с диском, а с
 * ребра ложится в черту. Окружностью тут не обойтись — круг остаётся кругом при любом
 * повороте, и диск читался бы наклейкой поверх схемы.
 *
 * Внутреннее кольцо обходит круг быстрее внешнего, как и положено веществу на орбите: об
 * этом говорит порядок, а скорость задаёт разметка.
 */
export const ACCRETION_RINGS = [26, 36, 48, 62];

/**
 * Кольцо аккреционного диска: эллипс в плоскости Галактики вокруг точки {@code cx, cy},
 * радиусом {@code radius} в единицах поля.
 *
 * Считается только поворотом, без масштаба и перспективы: размер задан в единицах поля
 * нарочно (см. {@link ACCRETION_RINGS}), и множить его на масштаб схемы значило бы вернуть
 * диску его настоящий — то есть невидимый — размер.
 */
export const accretionRing = (
  radius: number,
  cx: number,
  cy: number,
  view: ViewAngles,
  segments = 44,
): string => {
  const yaw = (view.yawDeg * Math.PI) / 180;
  const pitch = (view.pitchDeg * Math.PI) / 180;
  const roll = ((view.rollDeg ?? 0) * Math.PI) / 180;
  return Array.from({ length: segments + 1 }, (_, index) => {
    const angle = (2 * Math.PI * index) / segments;
    // Точка кольца в плоскости диска, единичным радиусом.
    const gx = Math.cos(angle);
    const gy = Math.sin(angle);
    const spunX = gx * Math.cos(yaw) - gy * Math.sin(yaw);
    // Высоты у кольца нет (оно в самой плоскости), поэтому от наклона остаётся один
    // косинус — он и сплющивает эллипс.
    const tilted = (gx * Math.sin(yaw) + gy * Math.cos(yaw)) * Math.cos(pitch);
    const x = spunX * Math.cos(roll) - tilted * Math.sin(roll);
    const y = spunX * Math.sin(roll) + tilted * Math.cos(roll);
    return `${(cx + x * radius).toFixed(1)},${(cy + y * radius).toFixed(1)}`;
  }).join(' ');
};

