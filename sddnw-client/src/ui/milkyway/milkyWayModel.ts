/** Куда смотрит наблюдатель и насколько близко. */
export interface ViewAngles {
  /** Поворот вокруг оси Галактики, градусы. */
  yawDeg: number;
  /** Наклон плоскости диска к наблюдателю: 0° — плашмя, 90° — с ребра. */
  pitchDeg: number;
  /**
   * Крен — поворот всей картины в плоскости экрана, градусы.
   *
   * Третий угол нужен затем, зачем и первые два: у Галактики нет «верха», и смотреть на
   * неё можно откуда угодно. Поворот и наклон дают направление взгляда, крен — как при
   * этом повёрнута голова наблюдателя; без него диск всегда ложился на экран одним и тем
   * же боком, и сцена смотрелась макетом на подставке.
   */
  rollDeg: number;
  zoom: number;
}

/**
 * Пределы приближения — общие у колеса мыши и у ползунка.
 *
 * Разойдись они, и ползунок показывал бы своё крайнее значение, пока схема стоит в
 * другом: два предела на одну величину всегда однажды расходятся.
 */
export const ZOOM_MIN = 0.6;
export const ZOOM_MAX = 2.2;

export interface ProjectedElement {
  element: GalaxyElement;
  /** Экранные координаты в пикселях поля. */
  x: number;
  y: number;
  /** Глубина: больше — ближе к наблюдателю. По ней элементы и сортируются. */
  depth: number;
  /** Во сколько раз точка ближе или дальше середины — размер и яркость берутся отсюда. */
  perspective: number;
}

/**
 * Насколько далеко наблюдатель, в радиусах диска. Чем ближе, тем сильнее перспектива;
 * на трёх радиусах ближний край крупнее дальнего примерно вдвое — этого хватает, чтобы
 * увидеть объём, и не настолько много, чтобы схема кривилась.
 */
const CAMERA_DISTANCE = 3;

/**
 * Всё, что в повороте одинаково для всех точек: синусы углов, масштаб и середина поля.
 *
 * Считается раз на кадр. Раньше каждая точка считала свои четыре синуса заново — на сотне
 * точек это не замечалось, на девяти тысячах стало половиной кадра.
 */
export interface ViewBasis {
  cosYaw: number;
  sinYaw: number;
  cosPitch: number;
  sinPitch: number;
  /** Крен: поворот готовой проекции в плоскости экрана. */
  cosRoll: number;
  sinRoll: number;
  scale: number;
  halfX: number;
  halfY: number;
}

/**
 * Поле схемы прямоугольное, а Галактика круглая: масштаб берётся по меньшей стороне,
 * поэтому диск всегда влезает целиком, а лишняя ширина достаётся тому, что за его краем, —
 * шаровым скоплениям гало и ближней половине диска, растянутой перспективой. Раньше поле
 * было квадратным, и всё это обрезалось по бокам.
 */
export const viewBasis = (view: ViewAngles, width: number, height: number): ViewBasis => {
  const yaw = (view.yawDeg * Math.PI) / 180;
  const pitch = (view.pitchDeg * Math.PI) / 180;
  const roll = ((view.rollDeg ?? 0) * Math.PI) / 180;
  return {
    cosYaw: Math.cos(yaw),
    sinYaw: Math.sin(yaw),
    cosPitch: Math.cos(pitch),
    sinPitch: Math.sin(pitch),
    cosRoll: Math.cos(roll),
    sinRoll: Math.sin(roll),
    scale: ((Math.min(width, height) / 2) * view.zoom) / (DISK_RADIUS_LY * 1.35),
    halfX: width / 2,
    halfY: height / 2,
  };
};

/**
 * Поворот одной точки и её проекция на экран — по готовому базису.
 *
 * Порядок поворотов: сперва вокруг оси Галактики (yaw), потом наклон к наблюдателю
 * (pitch). Обратный порядок дал бы вращение вокруг экранной оси, а не вокруг самой
 * Галактики, — схема бы кувыркалась.
 */
export const toScreenWith = (
  point: { x: number; y: number; z: number },
  basis: ViewBasis,
): { x: number; y: number; depth: number; perspective: number } => {
  const spunX = point.x * basis.cosYaw - point.y * basis.sinYaw;
  const spun = point.x * basis.sinYaw + point.y * basis.cosYaw;
  // Наклон: часть «глубины» забирает себе экранная вертикаль.
  const tilted = spun * basis.cosPitch - point.z * basis.sinPitch;
  const depth = spun * basis.sinPitch + point.z * basis.cosPitch;
  const perspective = CAMERA_DISTANCE / (CAMERA_DISTANCE - depth / DISK_RADIUS_LY);
  // Крен — поворот УЖЕ ПОСЧИТАННОЙ проекции: он ничего не меняет в глубине, поэтому
  // стоит последним и в сортировку по глубине не вмешивается.
  const x = spunX * basis.cosRoll - tilted * basis.sinRoll;
  const y = spunX * basis.sinRoll + tilted * basis.cosRoll;

  return {
    x: basis.halfX + x * basis.scale * perspective,
    y: basis.halfY + y * basis.scale * perspective,
    depth,
    perspective,
  };
};

/**
 * То же для одиночной точки, когда базис считать незачем: край диска, пузыри Ферми,
 * полюса. Их в кадре десятки, а не тысячи.
 */
export const toScreen = (
  point: { x: number; y: number; z: number },
  view: ViewAngles,
  width: number,
  height: number,
): { x: number; y: number; depth: number; perspective: number } =>
  toScreenWith(point, viewBasis(view, width, height));

/**
 * Поворот и проекция всей схемы.
 *
 * Возвращается список, отсортированный от дальних к ближним: SVG рисует в порядке
 * следования, и без сортировки дальние скопления оказывались бы поверх ближних.
 */
export const project = (
  elements: GalaxyElement[],
  view: ViewAngles,
  width: number,
  height: number,
): ProjectedElement[] => {
  const basis = viewBasis(view, width, height);
  return elements
    .map((element) => ({ element, ...toScreenWith(element, basis) }))
    .sort((left, right) => left.depth - right.depth);
};

/**
 * Кольцо радиусом `radiusLy` на высоте `heightLy` над плоскостью диска — готовые точки
 * для `polyline`.
 *
 * Точки идут по порядку обхода и по глубине не сортируются: сортировка смешала бы их и
 * превратила кольцо в зигзаг.
 */
export const ringPoints = (
  radiusLy: number,
  heightLy: number,
  view: ViewAngles,
  width: number,
  height: number,
  segments = 48,
): string => {
  const basis = viewBasis(view, width, height);
  return Array.from({ length: segments + 1 }, (_, index) => {
    const angle = (2 * Math.PI * index) / segments;
    const point = toScreenWith(
      {
        x: radiusLy * Math.cos(angle),
        y: radiusLy * Math.sin(angle),
        z: heightLy,
      },
      basis,
    );
    return `${point.x.toFixed(1)},${point.y.toFixed(1)}`;
  }).join(' ');
};

/**
 * Край диска: по нему и читается, как схема повёрнута. Сам он не элемент схемы — это
 * подсказка о положении плоскости, а не часть Галактики.
 */
export const diskRing = (view: ViewAngles, width: number, height: number): string =>
  ringPoints(DISK_RADIUS_LY, 0, view, width, height, 64);

