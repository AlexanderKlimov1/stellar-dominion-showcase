import type { Key } from '../../i18n';

/**
 * Схема Млечного Пути — демонстрационная сцена из главного меню.
 *
 * Схема двухслойная: сотня именованных элементов (чёрная дыра, перемычка, рукава, отрог,
 * шаровые скопления и Солнце) держит форму, а сто тысяч звёзд фона дают ей плотность — без
 * них Галактика выглядит чертежом, а не звёздным островом. Всего сто тысяч сто точек.
 * <p>
 * <b>Звёзды и именованные элементы устроены по-разному, и это главное в модуле.</b>
 * Именованных сто: у каждого имя, вид и подпись, они живут объектами и рисуются SVG.
 * Звёзд сто тысяч: объектов на них не заводится вовсе — координаты лежат в
 * {@link StarField} тремя {@code Float32Array}, а рисует их канва
 * ({@code milkyWayStarfield.ts}) пиксель за пикселем. Сто тысяч объектов заняли бы
 * мегабайты и считались бы кадрами; массивы считаются миллисекундами.
 *
 * Это не часть партии: галактика игры генерируется сервером и к настоящей Галактике
 * отношения не имеет. Схема нужна, чтобы показать в игре про космос сам космос, поэтому
 * живёт целиком на клиенте — сервер о ней ничего не знает и знать не должен.
 *
 * <b>Числа — общепринятые оценки, а не выдумка:</b> диаметр диска около 100 000 световых
 * лет, толщина тонкого диска около 1 000, перемычка в центре примерно 27 000 в длину,
 * Солнце в 26 000 световых лет от центра, в отроге Ориона между рукавами Стрельца и
 * Персея. Главных рукавов четыре: Наугольника, Щита — Центавра, Стрельца и Персея.
 *
 * <b>Строение — по инфракрасному обзору Spitzer (2008).</b> Главных рукавов два, и оба
 * отходят от концов перемычки: Щита — Центавра и Персея. Наугольника и Стрельца —
 * второстепенные: в них меньше старых звёзд, зато больше газа и областей звездообразования.
 * Раньше все четыре были одинаковыми, отчего схема и читалась вертушкой, а не галактикой.
 * <p>
 * Шаг спирали — 12–16°, как у настоящих рукавов Галактики (у Стрельца около 12°, у Персея
 * 16,5°). При таком шаге рукав делает почти полтора оборота: прежние 195° разворачивали
 * его в вертушку, но на сотне точек иначе было нельзя — теперь точек сто тысяч.
 * <p>
 * <b>Упрощение одно:</b> точка схемы не звезда и не скопление, а участок диска; звёзд в
 * Галактике порядка ста миллиардов, и сто тысяч точек передают только форму.
 *
 * Состав схемы задан таблицей {@link COMPOSITION}: из неё же считается и общее число
 * элементов, поэтому число в подписи не разъедется с тем, что нарисовано.
 */

/** Радиус диска в световых годах: диаметр Галактики около 100 000 св. лет. */
export const DISK_RADIUS_LY = 50_000;

/** Толщина тонкого диска, световые годы: точки разбросаны по ней в обе стороны. */
const DISK_THICKNESS_LY = 1_000;

/** Половина длины центральной перемычки: вся она около 27 000 св. лет. */
const BAR_HALF_LY = 13_500;

/** Угол перемычки к направлению на Солнце — около 27°. */
const BAR_ANGLE = (27 * Math.PI) / 180;

/** Расстояние от центра Галактики до Солнца, световые годы. */
const SUN_RADIUS_LY = 26_000;


/**
 * Начало рукава по радиусу, световые годы, — запасное значение.
 *
 * Своё начало и свой конец теперь у каждого рукава ({@link ARMS}): одинаковая длина у всех
 * четырёх и была половиной той чертёжной правильности, от которой схема выглядела
 * вертушкой. Эта постоянная осталась затем, чтобы {@code armAngle} работал и на рукаве,
 * у которого своё начало не задано.
 */
const ARM_INNER_LY = 6_000;

/**
 * Ширина рукава поперёк, световые годы. Рукав — не линия, а поток шириной в тысячи
 * световых лет, и к краю диска он расплывается: множитель растёт с радиусом.
 */
const ARM_WIDTH_LY = 4_200;

/**
 * Разброс точек поперёк рукава: без него рукав выглядит проволокой, а не потоком.
 * Больше полутора тысяч брать нельзя: на восемнадцати точках разброс съедает самую
 * спираль, и четыре рукава превращаются в облако.
 */
const ARM_SCATTER_LY = 1_600;

export type ElementKind =
  | 'blackhole'
  | 'bar'
  | 'arm'
  | 'spur'
  | 'halo'
  | 'sun'
  | 'star';

export interface GalaxyElement {
  id: string;
  kind: ElementKind;
  /** Координаты в световых годах: плоскость диска — XY, толщина — Z. */
  x: number;
  y: number;
  z: number;
  /** Подпись у конца рукава, у Солнца и у чёрной дыры; у остальных точек её нет. */
  label?: string;
}

/**
 * Поле звёзд фона — сто тысяч точек в типизированных массивах.
 *
 * Не объекты: объект на звезду — это сто тысяч объектов, которые сборщик мусора будет
 * трогать на каждом кадре вращения. Массивы лежат сплошняком, читаются подряд и живут
 * ровно столько, сколько открыта сцена.
 *
 * @param tone цвет звезды: 0 — голубовато-белая молодая, 1 — жёлтая, 2 — красноватая
 *             старая, 3 — розовая область звездообразования. Тон берётся не наобум: в
 *             рукавах звёзды молодые и голубые, в балдже старые и красные, а розовые узлы
 *             стоят только в рукавах — как на снимках спиральных галактик.
 */
export interface StarField {
  x: Float32Array;
  y: Float32Array;
  z: Float32Array;
  tone: Uint8Array;
  /** Яркость звезды: 0 — рядовая, 1 — заметная, 2 — яркое светило. */
  bright: Uint8Array;
  count: number;
}

/** Градусы в радианы — углы рукавов записаны градусами, их так читают на картах. */
const rad = (degrees: number): number => (degrees * Math.PI) / 180;

/**
 * Рукава: где начинается, как круто закручен, сколько несёт звёзд и докуда тянется.
 *
 * <b>Ни одна пара чисел здесь не повторяется, и это главное.</b> Раньше рукава стояли
 * ровно через 90°, главные несли поровну и второстепенные поровну — схема выходила
 * вертушкой с двумя осями симметрии, какой ни одна галактика не бывает. Настоящие рукава
 * разные: у каждого свой шаг спирали, своя густота, своя длина, и отходят они от
 * перемычки не под прямым углом друг к другу.
 *
 * Числа — по обзору Spitzer (2008) и картам Млечного Пути: два главных рукава (Щита —
 * Центавра и Персея) от концов перемычки, два второстепенных между ними, шаг 11–16°.
 * Точнее их не знает никто: вид Галактики изнутри восстанавливают по счётам звёзд, и
 * расхождения между картами больше, чем разница между этими числами.
 */
const ARMS = [
  // Главные: отходят от концов перемычки, поэтому и начинаются под её углом.
  { code: 'scutum', name: 'mw.arm.scutum', start: BAR_ANGLE + rad(4), pitchDeg: 12.5,
    share: 0.31, major: true, innerLy: 5_600, outerLy: 46_000, width: 1 },
  { code: 'perseus', name: 'mw.arm.perseus', start: BAR_ANGLE + rad(176), pitchDeg: 15.5,
    share: 0.27, major: true, innerLy: 7_000, outerLy: 50_000, width: 1.15 },
  // Второстепенные: между главными, звёзд в них заметно меньше, и лежат они не посередине.
  { code: 'norma', name: 'mw.arm.norma', start: BAR_ANGLE + rad(97), pitchDeg: 10.5,
    share: 0.16, major: false, innerLy: 6_200, outerLy: 38_000, width: 0.8 },
  { code: 'sagittarius', name: 'mw.arm.sagittarius', start: BAR_ANGLE + rad(262), pitchDeg: 13.5,
    share: 0.26, major: false, innerLy: 5_200, outerLy: 44_000, width: 0.95 },
];

/**
 * Состав схемы. Правится здесь: и число элементов в подписи, и сама схема считаются
 * отсюда, поэтому разъехаться им негде.
 */
export const COMPOSITION = [
  { kind: 'blackhole' as ElementKind, name: 'mw.part.blackhole' as Key, count: 1 },
  { kind: 'bar' as ElementKind, name: 'mw.part.bar' as Key, count: 11 },
  { kind: 'arm' as ElementKind, name: 'mw.part.arm' as Key, count: ARMS.length * 18 },
  { kind: 'spur' as ElementKind, name: 'mw.part.spur' as Key, count: 8 },
  { kind: 'halo' as ElementKind, name: 'mw.part.halo' as Key, count: 7 },
  { kind: 'sun' as ElementKind, name: 'mw.part.sun' as Key, count: 1 },
  { kind: 'star' as ElementKind, name: 'mw.part.star' as Key, count: 100_000 },
];

/** Сколько всего элементов на схеме — сумма состава, а не записанное рядом число. */
export const ELEMENT_COUNT = COMPOSITION.reduce((sum, part) => sum + part.count, 0);

const countOf = (kind: ElementKind): number =>
  COMPOSITION.find((part) => part.kind === kind)?.count ?? 0;

/**
 * Разброс без случайности: схема должна быть одной и той же при каждой отрисовке, а
 * `Math.random` перерисовывал бы Галактику заново на каждом кадре вращения.
 *
 * Дробная часть большого синуса — обычный приём для такого «шума»: значение от 0 до 1,
 * непохожее у соседних номеров и всегда одно и то же у одного номера.
 */
const noise = (seed: number): number => {
  const value = Math.sin(seed * 127.1 + 311.7) * 43_758.545;
  return value - Math.floor(value);
};

/** То же, но от −1 до 1: так удобнее разбрасывать в обе стороны от середины. */
const spread = (seed: number): number => noise(seed) * 2 - 1;

/**
 * Рукав — логарифмическая спираль, но точки на нём стоят ровно по радиусу.
 * <p>
 * Если шагать ровно по углу, то почти все восемнадцать точек собираются у центра
 * (радиус растёт экспонентой), и вместо рукавов выходит комок в середине и пара точек на
 * краю. Поэтому радиус берётся ровными шагами, а угол считается по нему из уравнения
 * спирали: форма та же, а точки распределены по всей длине рукава.
 */
/**
 * Угол рукава на этом радиусе — логарифмическая спираль с шагом самого рукава.
 *
 * Шаг (pitch) — угол между рукавом и окружностью: чем он меньше, тем туже закручен рукав.
 * У Галактики это 12–16°, и при них рукав делает почти полтора оборота.
 */
const armAngle = (
  radius: number,
  arm: { start: number; pitchDeg: number; innerLy?: number },
): number =>
  arm.start
    + Math.log(radius / (arm.innerLy ?? ARM_INNER_LY)) / Math.tan((arm.pitchDeg * Math.PI) / 180);

/**
 * Где стоит Солнце по кругу — ровно между рукавами Стрельца и Персея.
 *
 * Считается по самим рукавам, а не задаётся числом: отрог Ориона, в котором мы живём, —
 * перемычка между этими двумя рукавами, и стоит ей разъехаться с ними при правке шага
 * спирали, как Солнце окажется посреди рукава, где ему не место.
 */
const SUN_ANGLE = ((): number => {
  const sagittarius = armAngle(SUN_RADIUS_LY, ARMS[3]);
  const perseus = armAngle(SUN_RADIUS_LY, ARMS[1]);
  // Ближайшее представление угла Персея: рукава заданы началом, и разность может уехать
  // на полный оборот.
  let delta = perseus - sagittarius;
  while (delta > Math.PI) {
    delta -= 2 * Math.PI;
  }
  while (delta < -Math.PI) {
    delta += 2 * Math.PI;
  }
  return sagittarius + delta / 2;
})();

function buildArms(): GalaxyElement[] {
  const perArm = countOf('arm') / ARMS.length;
  return ARMS.flatMap((arm, armIndex) =>
    Array.from({ length: perArm }, (_, index) => {
      const t = index / (perArm - 1);
      // Длина у каждого рукава своя — метки идут по ней, иначе короткий рукав Наугольника
      // дотягивался бы метками до края диска, где его самого уже нет.
      const radius = arm.innerLy + (arm.outerLy - arm.innerLy) * t;
      const angle = armAngle(radius, arm);
      // Разброс поперёк рукава растёт к краю: у центра рукава туго свиты, к краю
      // расходятся — так это и выглядит на картах Галактики.
      const scatter = ARM_SCATTER_LY * (0.3 + t) * spread(armIndex * 71 + index);
      return {
        id: `${arm.code}-${index}`,
        kind: 'arm' as ElementKind,
        x: (radius + scatter) * Math.cos(angle),
        y: (radius + scatter) * Math.sin(angle),
        z: (DISK_THICKNESS_LY / 2) * spread(armIndex * 133 + index * 7),
        // Подпись у самой дальней точки рукава: там она ничего не загораживает.
        label: index === perArm - 1 ? arm.name : undefined,
      };
    }),
  );
}

/**
 * Перемычка: вытянутое ядро поперёк центра. Точки гуще к середине (потому и берётся
 * квадрат доли), а по толщине разбросаны шире диска — балдж заметно толще.
 */
function buildBar(): GalaxyElement[] {
  const count = countOf('bar');
  return Array.from({ length: count }, (_, index) => {
    const t = (index / (count - 1)) * 2 - 1;
    const along = BAR_HALF_LY * Math.sign(t) * t * t;
    const across = 2_200 * spread(index * 37);
    return {
      id: `bar-${index}`,
      kind: 'bar' as ElementKind,
      x: along * Math.cos(BAR_ANGLE) - across * Math.sin(BAR_ANGLE),
      y: along * Math.sin(BAR_ANGLE) + across * Math.cos(BAR_ANGLE),
      z: 1_500 * spread(index * 53),
    };
  });
}

/**
 * Отрог Ориона — короткая перемычка между рукавами Стрельца и Персея, в которой стоит
 * Солнце. Он не главный рукав, поэтому и точек в нём вчетверо меньше.
 */
function buildSpur(): GalaxyElement[] {
  const count = countOf('spur');
  return Array.from({ length: count }, (_, index) => {
    const t = index / (count - 1) - 0.5;
    const angle = SUN_ANGLE + t * 0.55;
    const radius = SUN_RADIUS_LY + t * 9_000 + 1_200 * spread(index * 91);
    return {
      id: `spur-${index}`,
      kind: 'spur' as ElementKind,
      x: radius * Math.cos(angle),
      y: radius * Math.sin(angle),
      z: (DISK_THICKNESS_LY / 2) * spread(index * 17),
    };
  });
}

/**
 * Шаровые скопления гало: они и есть то, из-за чего схему стоит вращать — только по ним
 * видно, что Галактика не плоская картинка. Разложены по сфере вокруг центра.
 */
function buildHalo(): GalaxyElement[] {
  const count = countOf('halo');
  return Array.from({ length: count }, (_, index) => {
    const radius = 42_000 + 26_000 * noise(index * 23);
    const azimuth = 2 * Math.PI * noise(index * 61);
    // Наклон к плоскости диска: не ниже 25°, иначе скопление тонет в самом диске.
    const rise = (25 + 50 * noise(index * 97)) * (index % 2 === 0 ? 1 : -1);
    const polar = (rise * Math.PI) / 180;
    return {
      id: `halo-${index}`,
      kind: 'halo' as ElementKind,
      x: radius * Math.cos(polar) * Math.cos(azimuth),
      y: radius * Math.cos(polar) * Math.sin(azimuth),
      z: radius * Math.sin(polar),
    };
  });
}

/**
 * Длина, на которой плотность диска падает в e раз, световые годы. У Млечного Пути её
 * оценивают в 8–14 тысяч; берём верхнюю оценку — при ней диск заполнен до самого края,
 * а не собран в пятно у центра.
 */
const DISK_SCALE_LY = 14_000;

/**
 * Обрезка распределения ровно по краю диска. Без неё пара процентов звёзд выпадала бы
 * за 50 000 световых лет, и обрезанные по краю ложились бы кольцом прямо на границу
 * диска — ровный ободок из точек там, где ему взяться неоткуда.
 */
const DISK_CUTOFF = 1 - Math.exp(-DISK_RADIUS_LY / DISK_SCALE_LY);

/** Доля звёзд в балдже с перемычкой: центр Галактики плотнее всего. */
const BULGE_SHARE = 0.16;

/**
 * Просвет вокруг чёрной дыры, световые годы.
 *
 * Держится он не на красоте, а на деле: <b>в видимом свете центр Галактики не виден
 * вовсе</b> — его закрывают десятки звёздных величин пыли, и Sgr A* нашли в радио и в
 * инфракрасном. Поэтому у схемы, нарисованной «как видно глазу», в середине и положен
 * тёмный провал, а не выжженное добела пятно, в котором тонет сама дыра.
 *
 * Звёзды из просвета не выбрасываются, а раздвигаются наружу: счёт звёзд остаётся ровным
 * (сто тысяч — это число в подписи), а середина освобождается.
 */
const NUCLEUS_GAP_LY = 3_400;

/**
 * Кособокость диска: на сколько и в какую сторону Галактика смещена относительно своего
 * центра.
 *
 * Идеально круглых галактик не бывает — почти у каждой спиральной диск скошен на
 * несколько процентов (астрономы зовут это lopsidedness, m = 1). Пять процентов не
 * бросаются в глаза, но снимают ровно то ощущение чертёжной правильности, из-за которого
 * схема выглядела циркулем, а не фотографией.
 */
const LOPSIDED = 0.055;
const LOPSIDED_ANGLE = (200 * Math.PI) / 180;

/**
 * Доля звёзд в рукавах. Остальное — межрукавный диск, где звёзды тоже есть.
 *
 * Шесть десятых оказались перебором: рукава выходили яркими лентами на чёрном, и схема
 * читалась чертежом спирали, а не снимком. На фотографиях спиральных галактик рукав —
 * это УПЛОТНЕНИЕ диска, а не лента в пустоте: между рукавами звёзд лишь немногим меньше.
 */
const ARM_SHARE = 0.4;

/**
 * Насколько перемычка вытянута и сплюснута. Настоящая — около 27 000 световых лет в
 * длину, поэтому вытягиваем вдвое от восьми тысяч и вдвое же сжимаем поперёк: выходит
 * брусок, а не шар, и именно он читается на снимках как «перемычка».
 */
const BAR_STRETCH = 1.7;
const BAR_SQUEEZE = 0.55;
const BULGE_RADIUS_LY = 8_000;

/**
 * Пылевая полоса вдоль внутренней кромки рукава. Тёмные полосы — первое, по чему на
 * снимке узнаётся спираль: пыль скапливается там, где волна плотности поджимает газ.
 * Звёзды из полосы не выбрасываются, а отодвигаются наружу — счёт звёзд остаётся ровным,
 * а полоса получается настоящей, с пустотой внутри.
 */
const DUST_LANE_FROM = -1.05;
const DUST_LANE_TO = -0.5;

/**
 * Звёзды фона — сто тысяч точек, из которых и состоит сама Галактика.
 *
 * Три населения, и каждое лежит по-своему:
 * <ul>
 *   <li><b>Балдж с перемычкой</b> — плотный вытянутый брусок в центре, старые красноватые
 *       светила, толстый по высоте;</li>
 *   <li><b>рукава</b> — потоки шириной в тысячи световых лет вдоль логарифмических
 *       спиралей: главные несут вдвое больше звёзд, чем второстепенные, к краю расплываются
 *       и подсвечены голубыми молодыми звёздами и розовыми областями звездообразования;</li>
 *   <li><b>межрукавный диск</b> — ровный фон между рукавами: пустых промежутков в
 *       Галактике нет, рукав лишь уплотняет то, что и так есть.</li>
 * </ul>
 *
 * Плотность падает от центра к краю экспонентой, как у настоящего диска: радиус берётся
 * через логарифм равномерного числа — так из ровного шума выходит именно падающая
 * плотность.
 *
 * Прежде звёзды притягивались к ближайшему рукаву целиком, и рукава выходили резаными
 * лентами с пустотой между ними — вертушка, а не галактика. Теперь звезда сразу
 * приписана своему рукаву и отклоняется от него на случайную величину: край рукава
 * размывается сам, как на снимках.
 */
function buildStarField(): StarField {
  const count = countOf('star');
  const field: StarField = {
    x: new Float32Array(count),
    y: new Float32Array(count),
    z: new Float32Array(count),
    tone: new Uint8Array(count),
    bright: new Uint8Array(count),
    count,
  };

  for (let index = 0; index < count; index += 1) {
    const seed = index * 13 + 5;
    const population = noise(seed * 3.7);

    let radius: number;
    let angle: number;
    let thickness: number;
    let tone: number;

    if (population < BULGE_SHARE) {
      // Балдж с перемычкой: брусок под углом 27° к направлению на Солнце.
      // Просвет в середине: звёзды балджа начинаются не от самой дыры, а поодаль — там,
      // где в видимом свете их и правда видно (ближе всё закрыто пылью).
      const inner = NUCLEUS_GAP_LY
        + (BULGE_RADIUS_LY - NUCLEUS_GAP_LY) * Math.pow(noise(seed * 5.1), 0.6);
      const around = 2 * Math.PI * noise(seed * 2.3);
      // Концы перемычки разные: ближний к нам конец у Млечного Пути заметно богаче, и
      // ровный эллипс здесь выглядел бы деталью чертежа.
      const lopside = 1 + 0.18 * Math.cos(around);
      const along = inner * Math.cos(around) * BAR_STRETCH * lopside;
      const across = inner * Math.sin(around) * BAR_SQUEEZE;
      const x = along * Math.cos(BAR_ANGLE) - across * Math.sin(BAR_ANGLE);
      const y = along * Math.sin(BAR_ANGLE) + across * Math.cos(BAR_ANGLE);
      radius = Math.hypot(x, y);
      angle = Math.atan2(y, x);
      // Балдж толстый: в нём звёзды старые и разлетелись по высоте.
      thickness = 5_000 * (1 - 0.5 * (inner / BULGE_RADIUS_LY));
      // Старые красноватые, кое-где жёлтые.
      tone = noise(seed * 11.3) < 0.25 ? 1 : 2;
    } else if (population < BULGE_SHARE + ARM_SHARE) {
      // Рукав: сперва выбираем какой — главные тяжелее второстепенных.
      let pick = noise(seed * 8.9);
      let arm = ARMS[0];
      for (const candidate of ARMS) {
        if (pick < candidate.share) {
          arm = candidate;
          break;
        }
        pick -= candidate.share;
      }

      // Радиус: гуще у центра, но не так резко, как в межрукавном диске. Длина у каждого
      // рукава своя — Наугольника вдвое короче Персея.
      radius = arm.innerLy
        + (arm.outerLy - arm.innerLy) * Math.pow(noise(seed * 1.9), 0.75);

      // Поперёк рукава — сумма трёх шумов: она ложится колоколом, а один шум дал бы
      // ровную ленту с обрезанными краями.
      const bell = (noise(seed * 2.3) + noise(seed * 4.7) + noise(seed * 6.1)) / 3 * 2 - 1;
      const width = ARM_WIDTH_LY * arm.width * (0.45 + radius / DISK_RADIUS_LY);
      let offset = bell * width;
      // Пылевая полоса на внутренней кромке: звёзды из неё отодвигаются наружу.
      if (offset < DUST_LANE_TO * width && offset > DUST_LANE_FROM * width) {
        offset += (DUST_LANE_TO - DUST_LANE_FROM) * width;
      }

      // ИЗЛОМЫ ВДОЛЬ РУКАВА. Логарифмическая спираль — гладкая дуга, и четыре такие дуги
      // читаются чертежом, а не галактикой: настоящий рукав виляет, местами разбухает,
      // местами обрывается и идёт дальше отрогом. Два медленных синуса разной длины дают
      // ровно это, а фаза у каждого рукава своя — иначе виляли бы все разом.
      const phase = arm.start * 3.1;
      const wander = Math.sin(radius / 5_400 + phase) * 0.4
        + Math.sin(radius / 13_000 + phase * 1.7) * 0.32;
      offset += wander * width;

      // Смещение поперёк рукава — это угол на его радиусе; плюс лёгкая рябь вдоль,
      // от которой рукав перестаёт быть гладкой дугой.
      angle = armAngle(radius, arm) + offset / radius + 0.06 * spread(seed * 9.7);
      radius *= 1 + 0.03 * spread(seed * 12.3);
      thickness = DISK_THICKNESS_LY * (1.6 - radius / DISK_RADIUS_LY);
      // Молодые голубые — примета рукава; в главных их больше. Розовые точки — области
      // звездообразования, те самые розовые узлы на снимках спиральных галактик.
      const colour = noise(seed * 11.3);
      tone = colour < 0.03 ? 3 : colour < (arm.major ? 0.82 : 0.62) ? 0 : 1;
    } else {
      // Межрукавный диск: фон между рукавами, плотность падает экспонентой.
      radius = -DISK_SCALE_LY * Math.log(1 - DISK_CUTOFF * noise(seed * 1.9));
      // Просвет в середине — тот же, что у балджа: ближе к дыре звёзд в видимом свете нет.
      if (radius < NUCLEUS_GAP_LY) {
        radius = NUCLEUS_GAP_LY - (NUCLEUS_GAP_LY - radius) * 0.25;
      }
      angle = 2 * Math.PI * noise(seed * 2.3);
      // Фон не ровный по кругу: плавное сгущение с одной стороны и разрежение с другой.
      // Делается сдвигом самого угла — так звёзды сгущаются там, где карта угла сжата, и
      // это дешевле любого перебора с отбраковкой.
      angle += 0.2 * Math.sin(2 * angle + 0.9) + 0.12 * Math.sin(angle - 2.1);
      thickness = DISK_THICKNESS_LY * (1.6 - radius / DISK_RADIUS_LY);
      // Цвет по радиусу: у центра звёзды старше и желтее, к краю моложе и голубее — тот
      // самый градиент возраста, что виден на снимках спиральных галактик.
      tone = noise(seed * 11.3) < 0.15 + 0.5 * (radius / DISK_RADIUS_LY) ? 0 : 1;
    }

    // Кособокость диска: одна сторона Галактики вытянута чуть дальше другой. Делается
    // здесь, после всех населений, — иначе пришлось бы повторять в каждом из трёх.
    radius *= 1 + LOPSIDED * Math.cos(angle - LOPSIDED_ANGLE);

    field.x[index] = radius * Math.cos(angle);
    field.y[index] = radius * Math.sin(angle);
    field.z[index] = (thickness / 2) * spread(seed * 7.3);
    field.tone[index] = tone;
    // Яркость: почти все звёзды ровные, десятая часть заметнее, полтора процента —
    // яркие светила. Без них поле выглядит ровной крупой, а на снимках яркие звёзды
    // всегда наперечёт.
    const shine = noise(seed * 17.7);
    field.bright[index] = shine > 0.985 ? 2 : shine > 0.88 ? 1 : 0;
  }

  return field;
}

