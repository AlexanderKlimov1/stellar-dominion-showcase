/**
 * Как группы сторон расы разложены по столбцам окна race picks MOO II — п. 7.
 *
 * Раскладка взята со снимка оригинала (StrategyWiki, Race design options) и повторяет её
 * дословно:
 *
 * * **слева** — лестницы хозяйства: рост населения, еда, промышленность, наука, деньги;
 * * **посередине** — лестницы войны и разведки, а под ними правительства: защита кораблей,
 *   атака кораблей, наземный бой, шпионаж, правительство;
 * * **справа** — ОДИН список «особые способности», в который у оригинала сведено всё
 *   остальное: тяжесть родного мира, вместимость миров, родной мир, чем питается раса,
 *   отношение соседей, изобретательность, хозяйство и сами особые способности.
 *
 * Правый столбец потому и один список, что в оригинале он один: восемь заголовков на
 * двадцать две строки рвали столбец на клочки, а выбирают там по названию стороны, а не по
 * группе. Порядок групп внутри столбца задаёт порядок строк.
 *
 * Таблицей, а не порядком из справочника: в файле группы лежат в своём порядке
 * (правительство первым — так их читает сервер), а в окне оригинала правительство стоит
 * внизу среднего столбца. Эти два порядка не совпадают и совпадать не обязаны.
 *
 * Группа, которой в таблице не нашлось места, не пропадает: она уходит в правый столбец
 * последней — новая группа в справочнике должна быть видна игроку, даже если про неё
 * забыли здесь.
 */
export interface RaceColumn {
  /** Коды групп по порядку сверху вниз. */
  groups: string[];
  /**
   * Свой заголовок на весь столбец; у него тогда заголовков групп нет — так устроен
   * правый столбец оригинала.
   */
  heading?: 'special';
}

export const RACE_COLUMNS: RaceColumn[] = [
  { groups: ['growth', 'food', 'industry', 'science', 'money'] },
  { groups: ['ship-defense', 'ship-attack', 'ground', 'espionage', 'government'] },
  {
    heading: 'special',
    groups: ['gravity', 'population-capacity', 'homeworld', 'food-consumption',
      'diplomacy', 'creativity', 'economics', 'special'],
  },
];

/** Коды групп, которым в таблице место нашлось, — чтобы найти забытые. */
export const PLACED_GROUPS = new Set(RACE_COLUMNS.flatMap((column) => column.groups));
