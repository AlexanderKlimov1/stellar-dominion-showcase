/**
 * Accent — выделение числа на сцене одним свойством (решение хозяина проекта, 03.10.2026,
 * развитие backlog-promo, пункт 13).
 *
 * Число на экране выделяют три вещи разом — размер, цвет и начертание, — и прежде каждая
 * сцена подбирала их сама: казна на правой панели, цена в окне выкупа и сила флота были
 * числами одного смысла, а выглядели по-разному, и глаз не мог выучить, что крупное значит
 * «важное». Теперь число получает СТУПЕНЬ, и ступень решает всё: размер, цвет, начертание
 * числа и размер его значка. **Два числа с одной ступенью выглядят одинаково на любой
 * сцене** — подбирать классы числу по месту больше нельзя.
 *
 * Ступеней четыре, от главного к примечанию:
 *
 * * `key` — главное число экрана, ОДНО на экран (срок стройки колонии, еда в списке колоний,
 *   сила выбранного флота, своё место в «Инфо»); подпись у него стоит над числом;
 * * `lead` — заглавное число раздела или панели: казна и год на правой панели, доход в шапке
 *   колонии, цена в окне подтверждения, итог под таблицей;
 * * `value` — обычное значение: ячейка таблицы, строка характеристик, счёт в списке;
 * * `note` — сопутствующее число рядом со значением: прирост, содержание в скобках, подпись
 *   линии графика, второстепенная строка карточки.
 *
 * Состояние — не ступень: голод, долг и нехватка красные (`danger`), предупреждение жёлтое
 * (`warn`), удача зелёная (`good`) — на любой ступени, и меняют они ТОЛЬКО цвет, а размер и
 * начертание остаются за ступенью. Так «−5» в строке и «−5» в итоге отличаются весом, а не
 * тревогой.
 *
 * Значок ресурса рядом с числом (монеты, колос, молот) берёт размер и цвет у той же ступени:
 * число и его значок — одно обозначение, и разного веса у них быть не может.
 */
export type Accent = 'key' | 'lead' | 'value' | 'note';

/** Состояние, которое число сообщает само: меняет только цвет. */
export type Tone = 'danger' | 'warn' | 'good';

interface AccentStyle {
  /** Размер, начертание и межстрочье числа — ступени шкалы, никаких пикселей по месту. */
  readonly type: string;
  /** Цвет числа и значка, пока число не сообщает состояния. */
  readonly color: string;
  /** Размер значка рядом с числом. */
  readonly icon: string;
}

export const ACCENTS: Readonly<Record<Accent, AccentStyle>> = {
  key: { type: 'text-44 leading-none', color: 'text-ink-bright', icon: 'h-10 w-10' },
  lead: { type: 'text-24 leading-tight', color: 'text-ink-bright', icon: 'h-7 w-7' },
  value: { type: 'text-18 leading-snug', color: 'text-ink', icon: 'h-5 w-5' },
  note: { type: 'text-14 leading-snug', color: 'text-ink-soft', icon: 'h-4 w-4' },
};

const TONES: Readonly<Record<Tone, string>> = {
  danger: 'text-danger',
  warn: 'text-warn',
  good: 'text-good',
};

/**
 * Классы числа. Общие для всех ступеней: цифры одной ширины (столбцы не пляшут, когда число
 * меняется) и без переноса — «1 / 3» и «+15 gc», разорванные строкой, перестают быть числом.
 */
export const figureClass = (accent: Accent, tone?: Tone): string =>
  `${ACCENTS[accent].type} ${tone ? TONES[tone] : ACCENTS[accent].color} whitespace-nowrap tabular-nums`;

/** Классы значка при числе: размер ступени, цвет числа. */
export const figureIconClass = (accent: Accent, tone?: Tone): string =>
  `${ACCENTS[accent].icon} shrink-0 ${tone ? TONES[tone] : ACCENTS[accent].color}`;

/**
 * Классы слов ВОКРУГ числа — подписи и фразы, в которую число подставлено (`tf`). Кегль
 * подписи — кегль ступени: число 14-м кеглем посреди фразы 22-м выглядело бы опечаткой, а не
 * примечанием (так и вышло в шапке колонии при первом переводе). Цвет — приглушённый: ярким
 * в строке остаётся число. Поэтому и правило: в одной фразе все числа одной ступени.
 */
export const figureLabelClass = (accent: Accent): string =>
  `${ACCENTS[accent].type} ${accent === 'note' ? 'text-ink-faint' : 'text-ink-soft'}`;

/** Тон по знаку: минус — беда, остальное молчит. Самое частое правило, поэтому одно на игру. */
export const signTone = (n: number): Tone | undefined => (n < 0 ? 'danger' : undefined);

/** Число со знаком: «+15», «−3», «0». Знак минуса типографский: дефис рядом с плюсом выглядит короче и читается как тире. */
export const signed = (n: number): string => (n > 0 ? `+${n}` : n < 0 ? `−${Math.abs(n)}` : '0');
