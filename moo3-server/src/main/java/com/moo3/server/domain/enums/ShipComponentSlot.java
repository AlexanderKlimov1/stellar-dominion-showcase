package com.moo3.server.domain.enums;

/**
 * Куда встаёт компонент корабля — п. 8.
 * <p>
 * Разметка проекта повторяет окно дизайна MOO II: двигатель, броня, щит, компьютер и
 * постановщик помех у корабля по одному, а пушек и особых модулей — сколько влезет.
 * Отсюда и правило проверки: {@link #single()} говорит, можно ли поставить второй такой
 * компонент.
 * <p>
 * Второе правило — {@link #scalesWithHull()}. Броня, щиты, двигатели, приборы и особые
 * модули обслуживают весь корабль, поэтому их место и цена растут вместе с корпусом.
 * Пушка своё место не меняет: лазер на дредноуте занимает столько же, сколько на фрегате,
 * — из-за этого крупный корпус несёт пропорционально больше огня, как в MOO II.
 * <p>
 * <b>Это проверено по оригиналу, а не принято на веру.</b> Рост гнезда вместе с корпусом
 * здесь однажды завели — и откатили, разобрав снимок окна дизайна
 * (`docs/moo2/ship-design.png`): на нём ЛИНКОР в 250 клеток несёт десять ракетных гнёзд по
 * 21 клетке, то есть гнездо с тремя модификациями (MIRV +100 %, ECCM +25 %, FST +25 %)
 * стоит там около восьми клеток — столько же, сколько на фрегате. Растут в оригинале броня,
 * щит, двигатель и особые модули, а гнездо оружия — нет.
 * <p>
 * Поэтому и РАЗМЕРЫ самих стволов взяты оригинальские: у лучей со снарядами база десять
 * клеток на любом корпусе, у ионной пушки и разрушителя двадцать, у Дробителя и Копья новы
 * пятьдесят. Правятся они в `ship-components.json`, и там же названо, откуда числа.
 */
public enum ShipComponentSlot {

    /** Двигатель: скорость корабля. Обязателен — без него корабль не полетит. */
    ENGINE(true, true),

    /** Броня: очки, которые снимаются раньше прочности корпуса. */
    ARMOR(true, true),

    /** Щит: держит удар до брони. */
    SHIELD(true, true),

    /** Прицельный компьютер: поднимает залп в процентах. */
    COMPUTER(true, true),

    /** Постановщик помех: прибавка к защите. */
    ECM(true, true),

    /** Оружие: сколько угодно стволов, место у каждого своё и от корпуса не зависит. */
    WEAPON(false, false),

    /** Особый модуль: боевые отсеки, усиленный корпус, десант и прочее. */
    SPECIAL(false, true);

    private final boolean single;
    private final boolean scalesWithHull;

    ShipComponentSlot(boolean single, boolean scalesWithHull) {
        this.single = single;
        this.scalesWithHull = scalesWithHull;
    }

    /** Можно ли поставить в проект только один такой компонент. */
    public Boolean single() {
        return single;
    }

    /** Растут ли место и цена компонента вместе с корпусом. */
    public Boolean scalesWithHull() {
        return scalesWithHull;
    }
}
