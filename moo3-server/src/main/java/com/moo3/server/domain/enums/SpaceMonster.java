package com.moo3.server.domain.enums;

import java.util.List;

/**
 * Космические чудища MOO II — п. 11.1: они сторожат звёздные системы.
 * <p>
 * В оригинале чудище сидит в системе и нападает на всякий вошедший флот. Оно никуда не
 * летит, ничего не захватывает и ни с кем не договаривается — это препятствие, а не
 * империя: система с чудищем закрыта для расселения, пока его не убьют. Тем оно и ценно
 * для игры: хорошая планета за спиной у дракона стоит дороже такой же в чистом поле.
 * <p>
 * <b>Почему подсистемой, а не событием.</b> Справочник событий это и объяснял: чудище —
 * не происшествие на ход, у него есть место и здоровье, оно переживает десятки ходов и
 * решает, куда империи можно селиться. Событием такое не выражается.
 * <p>
 * <b>Сила — реконструкция.</b> MOO II числа чудищ не публиковала, известен лишь порядок:
 * амёба и кристалл по зубам молодой империи, дракон и гидра — середине партии, а Страж
 * не по зубам почти никому. Числа взяты в той же мере, в какой считается сила
 * флота ({@code ShipDesignRules.power}): фрегат первого хода весит около сорока, крейсер
 * с изученными пушками — несколько сотен.
 * <p>
 * <b>У чудища есть и ТЕЛО</b> — корпус справочника кораблей ({@code hullCode}, признак
 * {@code monster} в `ship-components.json`). Оно нужно тактическому бою: поле считает
 * только корабли, и чудище выходит на него телом, шкурой и когтями (п. 8, п. 11.1).
 * Сколько когтей — решает {@code MonsterBattleRules} по нынешней силе чудища, так что
 * сила остаётся единственным числом, которое правится здесь.
 *
 * @param label    имя чудища: его игрок видит на карте и в итогах хода
 * @param strength боевая сила — в той же мере, что и сила флота
 * @param weight   вес в жребии при заселении галактики: у мелких он больше
 * @param hullCode тело чудища в справочнике кораблей — им оно выходит на поле боя
 */
public enum SpaceMonster {

    /** «Космическая амёба»: самое слабое чудище, попадается чаще прочих. */
    AMOEBA("Космическая амёба", 120, 4, "amoeba-body"),

    /** «Космический кристалл»: медлителен, но твёрд. */
    CRYSTAL("Космический кристалл", 200, 3, "crystal-body"),

    /** «Космический угорь»: быстр и живуч. */
    EEL("Космический угорь", 320, 3, "eel-body"),

    /** «Гидра»: бьёт со всех голов разом. */
    HYDRA("Гидра", 500, 2, "hydra-body"),

    /** «Космический дракон»: середина партии, не раньше. */
    DRAGON("Космический дракон", 800, 2, "dragon-body"),

    /**
     * «Страж»: сильнейшее чудище галактики.
     * <p>
     * В первоисточнике такой страж сторожит особую звезду с её исключительной планетой.
     * Здесь особая звезда есть (Wardenhold, п. 4.2.1), но чудищ на неё генератор не
     * селит вовсе, поэтому Страж достаётся обычной системе. Точка расширения: поставить
     * его на Wardenhold — имя звезды об этом и говорит, — но тогда придётся решить, чем
     * такая система ценна, иначе она просто закрыта навсегда.
     */
    GUARDIAN("Страж", 2000, 1, "guardian-body");

    private final String label;
    private final int strength;
    private final int weight;
    private final String hullCode;

    SpaceMonster(String label, int strength, int weight, String hullCode) {
        this.label = label;
        this.strength = strength;
        this.weight = weight;
        this.hullCode = hullCode;
    }

    public String getLabel() {
        return label;
    }

    public Integer getStrength() {
        return strength;
    }

    public Integer getWeight() {
        return weight;
    }

    /** Тело чудища: корпус, которым оно выходит на поле тактического боя — п. 8, п. 11.1. */
    public String getHullCode() {
        return hullCode;
    }

    /** Чудища, какие бывают, — по ним и бросается жребий при заселении галактики. */
    public static List<SpaceMonster> all() {
        return List.of(values());
    }
}
