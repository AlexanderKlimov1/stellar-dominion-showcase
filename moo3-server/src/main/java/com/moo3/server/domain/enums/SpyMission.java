package com.moo3.server.domain.enums;

/**
 * Чем занят шпион у чужой империи — п. 13.
 * <p>
 * Как в MOO II: агента отправляют к сопернику и назначают ему дело. Он копит очки,
 * пока не наберёт на операцию, и тогда она случается — а дальше он копит снова.
 *
 * @see com.moo3.server.service.EspionageService
 */
public enum SpyMission {

    /**
     * Шпион работает дома: не покидает империю и прибавляет к её общему запасу очков
     * разведки. На эти очки уходят вылазки в чужие системы (п. 15).
     */
    HOME("Дома", 0),

    /** Кража технологии: у соперника забирается то, чего империя ещё не знает. */
    STEAL_TECH("Кража технологии", 20),

    /** Саботаж: срывает стройку одной из колоний соперника. */
    SABOTAGE("Саботаж", 15),

    /**
     * Контрразведка: агент остаётся дома и ловит чужих. Очков империи он не приносит —
     * его работа в том, чтобы отнимать их у чужих агентов.
     */
    COUNTER("Контрразведка", 0);

    private final String label;
    /**
     * Во сколько очков обходится операция.
     * <p>
     * Реконструкция: MOO II считает шпионаж броском против защиты соперника, и точных
     * чисел проверить не удалось. Взято так, чтобы агент готовил кражу около десяти
     * ходов, а саботаж — вдвое быстрее: кража ценнее и должна стоить дороже.
     */
    private final Integer cost;

    SpyMission(String label, Integer cost) {
        this.label = label;
        this.cost = cost;
    }

    public String getLabel() {
        return label;
    }

    public Integer getCost() {
        return cost;
    }
}
