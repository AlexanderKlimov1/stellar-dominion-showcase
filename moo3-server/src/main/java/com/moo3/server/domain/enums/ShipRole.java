package com.moo3.server.domain.enums;

/**
 * Для чего корабль построен — п. 8.
 * <p>
 * В MOO II три корабля не собираются в окне дизайна вовсе: колониальный корабль,
 * транспорт и корабль-заставу игра предлагает готовыми, прямо в списке стройки колонии,
 * и у каждого своя твёрдая цена. Здесь они те же проекты империи, но в служебной ячейке,
 * и роль отличает их от боевых.
 * <p>
 * Гражданский корабль в MOO II «уничтожается сразу, как только на него нападут, и на поле
 * боя даже не выходит». Отсюда и правило игры: в силу флота такой корабль не входит, в
 * тактический бой не встаёт, а проигранный бой уносит его вместе с флотом.
 */
public enum ShipRole {

    /** Боевой корабль: собран игроком в окне дизайна, воюет и держит систему. */
    WARSHIP("Боевой"),

    /** Колониальный корабль: везёт поселенцев и основывает колонию в чужой системе. */
    COLONY("Колониальный"),

    /** Транспорт: везёт десант — четыре бойца, как в оригинале. */
    TRANSPORT("Транспорт"),

    /**
     * Корабль-застава: ставит заставу на любой планете, даже негодной для жизни.
     * <p>
     * Жителей на заставе нет, зато империя дотягивается от неё топливом дальше — п. 8.
     * Без неё империя, окружённая поясами астероидов и газовыми гигантами, оставалась
     * запертой в четырёх парсеках вокруг родной звезды навсегда.
     */
    OUTPOST("Застава"),

    /**
     * Орбитальная или планетарная платформа обороны — п. 8, п. 11: звёздная база, боевая
     * станция, звёздная крепость и наземные батареи.
     * <p>
     * Не корабль: строится ЗДАНИЕМ колонии, никуда не летит и в список стройки кораблей не
     * попадает — оттого и роль отдельная, а не {@code WARSHIP}. В бою платформа при этом
     * дерётся наравне со всеми: те же пушки, та же броня, та же кривая попадания. Оружие
     * ей подбирает игра по изученному, как и шести ячейкам дизайна, — в MOO II платформа
     * всегда вооружена по последнему слову, и переделывать её вручную нельзя.
     */
    PLATFORM("Платформа обороны");

    private final String label;

    ShipRole(String label) {
        this.label = label;
    }

    public String getLabel() {
        return label;
    }

    /**
     * Воюет ли корабль: гражданский в бою не участвует и силы флоту не добавляет.
     * <p>
     * Платформа обороны здесь тоже НЕ боевая, и это не описка: признак отвечает на вопрос
     * «строится ли этот проект колонией и ходит ли он с флотом», а платформа не делает ни
     * того, ни другого. В бой её ставит своя дорога — оборона колонии, а не флот.
     */
    public Boolean isCombat() {
        return this == WARSHIP;
    }
}
