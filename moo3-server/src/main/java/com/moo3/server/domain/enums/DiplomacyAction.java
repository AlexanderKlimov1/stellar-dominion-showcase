package com.moo3.server.domain.enums;

/** Что игрок предлагает другой империи — п. 15. */
public enum DiplomacyAction {

    /** Предложить мир: принимается, если доверие достаточно высоко. */
    PROPOSE_PEACE,

    /** Предложить договор: торговый, исследовательский, пакт о ненападении или союз. */
    PROPOSE_TREATY,

    /** Разорвать договор: согласия не требует, но бьёт по доверию. */
    BREAK_TREATY,

    /** Потребовать дань: соглашаются от страха или от большой приязни. */
    DEMAND_TRIBUTE,

    /** Объявить войну: согласия не требует. */
    DECLARE_WAR,

    /**
     * Обмен технологиями — п. 15: своя технология за чужую.
     * <p>
     * В MOO II это самое ходовое дипломатическое действие: одна сторона хочет
     * определённую технологию и предлагает за неё свои. Согласие требуется.
     */
    EXCHANGE_TECH,

    /**
     * Подарить кредиты — п. 15: согласия не требует, подарок не отвергают.
     * <p>
     * Дарят, чтобы купить расположение: доверие растёт тем сильнее, чем крупнее подарок
     * относительно казны дарящего.
     */
    GIFT_CREDITS,

    /** Подарить технологию — п. 15: тот же расчёт, только платят знанием. */
    GIFT_TECH
}
