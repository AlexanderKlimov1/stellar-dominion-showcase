package com.moo3.server.domain.enums;

/**
 * Характер правителя империи ИИ — п. 15.
 * <p>
 * Шесть характеров MOO II. В оригинале они стоят в окне Report меню рас: «правитель
 * империи силикоидов — <i>агрессивный промышленник</i>», и по ним игрок судит, чего от
 * соседа ждать. Здесь они делают то же самое, только их ещё и видно в дипломатии.
 * <p>
 * Каждый характер описан двумя числами и одним порогом:
 * <ul>
 *   <li><b>Доверие за хорошее</b> ({@code gainPercent}) и <b>за плохое</b>
 *       ({@code lossPercent}) — насколько сильно характер принимает к сердцу подарки,
 *       договоры, отказы, разрывы и кражи. Ксенофоб, по описанию оригинала, «вдвое слабее
 *       принимает хорошее и вдвое сильнее плохое»; благородный «вдвое сильнее отзывается
 *       на нападения без повода и на диверсии».</li>
 *   <li><b>Перевес для войны</b> ({@code warAdvantagePercent}) — во сколько раз мощнее
 *       соседа надо быть, чтобы напасть; мощь империи (флот и население) считает
 *       {@code AiDiplomacyService}. Агрессивный «нападёт, как только
 *       решит, что ему это сойдёт с рук»; миролюбивый нападает редко; беспощадный
 *       «нападает почти без повода» и потому лезет в драку даже слабее соперника.</li>
 * </ul>
 * <p>
 * <i>Реконструкция:</i> сами числа оригинал не публикует — названы только направления
 * («вдвое сильнее», «нападает редко»), и они здесь и стоят: двойка, половина и пороги
 * перевеса, расставленные по описаниям. Правятся в одном месте — этом.
 * <p>
 * <b>Пороги перевеса понижены 15.09.2026 по замеру.</b> Были 70/120/150/150/200/300, и на
 * этой шкале воевал фактически один беспощадный: перевес меряется отношением мощи, а мощь
 * у восьми империй с ОДИНАКОВЫМИ стартовыми системами держится около единицы — порог выше
 * ста процентов не срабатывает почти никогда. Измерено: за 150 ходов восьми империй — одна
 * воюющая империя из восьми, НОЛЬ БОЁВ, ноль-одна высадка. Направления оригинала при этом
 * сохранены целиком: беспощадный лезет, уступая вдвое; агрессивный нападает при равенстве
 * («как только сойдёт с рук»); непредсказуемый и ксенофоб — при небольшом перевесе;
 * благородный — при заметном; миролюбивый — только при подавляющем. Изменилось не то, КОГО
 * считать воинственным, а на какой шкале это меряется.
 */
public enum AiPersonality {

    /**
     * Беспощадный: «нападает с малым поводом или без повода вовсе, жертвуя кораблями и
     * людьми ради цели». Воюет, даже уступая вдвое, — оттого и живёт недолго.
     */
    RUTHLESS("Беспощадный", 100, 100, 50),

    /**
     * Агрессивный: «нападёт в любой момент, когда окажется в выгодном положении».
     * Достаточно равенства сил — повод не нужен.
     */
    AGGRESSIVE("Агрессивный", 100, 100, 90),

    /**
     * Непредсказуемый: «в один год миролюбив, в другой пойдёт войной по любому поводу».
     * Порог перевеса у него средний, но решения его жребий — см.
     * {@code AiDiplomacyService}: там характер один умеет передумать.
     */
    ERRATIC("Непредсказуемый", 100, 100, 110),

    /**
     * Ксенофоб: «не доверяет никому — вдвое слабее принимает хорошее в дипломатии и вдвое
     * сильнее её враждебные шаги».
     */
    XENOPHOBIC("Ксенофоб", 50, 200, 110),

    /**
     * Благородный: «не нападает на тех, с кем в хороших отношениях, и вдвое сильнее
     * отзывается на нападения без повода и на диверсии».
     */
    HONORABLE("Благородный", 100, 200, 140),

    /**
     * Миролюбивый: «дорожит мирными отношениями и нападает редко; на войне быстрее просит
     * мира». Воюет только при подавляющем перевесе.
     */
    PACIFISTIC("Миролюбивый", 100, 100, 200);

    private final String label;
    private final int gainPercent;
    private final int lossPercent;
    private final int warAdvantagePercent;

    AiPersonality(String label, int gainPercent, int lossPercent, int warAdvantagePercent) {
        this.label = label;
        this.gainPercent = gainPercent;
        this.lossPercent = lossPercent;
        this.warAdvantagePercent = warAdvantagePercent;
    }

    public String getLabel() {
        return label;
    }

    /** Насколько сильно характер принимает хорошее: 100 — как все, 50 — вдвое слабее. */
    public Integer getGainPercent() {
        return gainPercent;
    }

    /** Насколько сильно характер принимает плохое: 100 — как все, 200 — вдвое сильнее. */
    public Integer getLossPercent() {
        return lossPercent;
    }

    /**
     * Какой перевес нужен, чтобы напасть, в процентах от мощи соперника.
     * 70 — нападёт и уступая, 300 — только при тройном превосходстве.
     */
    public Integer getWarAdvantagePercent() {
        return warAdvantagePercent;
    }

    /** Благородный не бьёт того, с кем в хороших отношениях, — п. 15. */
    public Boolean sparesFriends() {
        return this == HONORABLE;
    }

    /** Миролюбивый на войне быстрее просит мира — п. 15. */
    public Boolean seeksPeace() {
        return this == PACIFISTIC;
    }
}
