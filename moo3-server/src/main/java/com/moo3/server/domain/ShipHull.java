package com.moo3.server.domain;

/**
 * Корпус корабля из справочника — п. 8.
 * <p>
 * Корпус задаёт всё, чего компоненты не меняют: сколько в корабль влезет
 * ({@code space}), во что обойдётся сам корпус ({@code cost}), сколько он держит
 * ({@code structure}) и насколько в него легко попасть ({@code hitChancePercent} — из
 * MOO II: 20 % по фрегату и 100 % по Leviathan).
 * <p>
 * {@code systemFactor} — во сколько раз дороже и объёмнее становятся на этом корпусе
 * компоненты, обслуживающие весь корабль (броня, щит, двигатель, приборы). Оружие им не
 * подчиняется, см. {@link com.moo3.server.domain.enums.ShipComponentSlot}.
 *
 * @param command сколько командных очков забирает корабль: 1 у фрегата, 6 у Leviathan.
 *                Очков командования в игре ещё нет — число хранится для будущего
 *                содержания флота и показывается в проекте.
 */
public record ShipHull(
        String code,
        LocalizedText names,
        LocalizedText descriptions,
        Integer space,
        Integer cost,
        Integer structure,
        Integer command,
        Integer hitChancePercent,
        Integer systemFactor,
        String requiredTechCode,
        Integer sortOrder,
        /**
         * Корпус — орбитальная платформа, а не корабль: звёздная база, боевая станция,
         * звёздная крепость (п. 8, п. 11). Такой корпус нельзя ни собрать в окне дизайна,
         * ни заложить на стапеле — он приходит ЗДАНИЕМ колонии и стоит на её орбите.
         * Оружие, броня и приборы ему подбираются сами по изученному, как и шести ячейкам
         * проектов, — в MOO II платформа всегда вооружена по последнему слову.
         */
        Boolean platform,
        /**
         * Корпус НЕ НЕСЁТ ОРУЖИЯ вовсе — п. 11: планетарный щит.
         * <p>
         * Щит не стреляет, он держит: в MOO II он «запечатывает планету почти непроницаемым
         * полем» и уменьшает урон по колонии, а не наносит его. Здесь это выражено тем, что
         * в бою он стоит целью, которую нужно разбить, а сам огня не открывает.
         */
        Boolean unarmed,
        /**
         * Корпус — ТЕЛО КОСМИЧЕСКОГО ЧУДИЩА, а не корабль (п. 11.1): амёба, кристалл,
         * угорь, гидра, дракон, Страж.
         * <p>
         * Поле боя умеет считать только корабль — корпус, броню и стволы, — поэтому
         * чудище выражено корпусом. Игроку такой корпус не показывается нигде: ни в окне
         * дизайна, ни в списке стройки, ни в подборе лучшего оружия. Прячет его сам
         * справочник ({@code ShipCatalog.hulls}), а не место показа: платформы обороны
         * дважды просачивались туда, где их быть не должно, и второй раз этой ошибки
         * лучше не делать.
         */
        Boolean monster
) {

    /** Название на языке читателя — п. 3.5. */
    public String name() {
        return names.text();
    }

    /** Описание на языке читателя — п. 3.5. */
    public String description() {
        return descriptions == null ? null : descriptions.text();
    }

    /**
     * Уклонение корпуса: чем крупнее корабль, тем чаще по нему попадают. Считается от
     * шанса попадания MOO II, поэтому у Leviathan уклонения нет вовсе — его защита это
     * щиты, броня и приборы.
     */
    public Integer evasion() {
        return 100 - hitChancePercent;
    }
}
