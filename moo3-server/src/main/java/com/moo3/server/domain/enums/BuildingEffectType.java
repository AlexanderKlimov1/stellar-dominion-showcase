package com.moo3.server.domain.enums;

/**
 * Что здание или особенность расы даёт колонии — п. 10 и п. 7.
 * <p>
 * Действие это тип и количество: «еды с фермера — 1», «вместимости — 2». Действия одной
 * колонии складываются, поэтому и новое здание, и новая особенность расы описываются
 * набором таких пар в своём файле и не требуют правок кода. Раса работает на колонии
 * как вечная постройка, поэтому набор типов у них общий.
 */
public enum BuildingEffectType {

    /** Еда за ход независимо от числа фермеров. */
    FOOD_FLAT,

    /** Прибавка к еде с каждого фермера. */
    FOOD_PER_FARMER,

    /** Производство за ход независимо от числа рабочих. */
    PRODUCTION_FLAT,

    /** Прибавка к производству с каждого рабочего. */
    PRODUCTION_PER_WORKER,

    /**
     * Производство с каждого жителя колонии, чем бы он ни был занят, — п. 10.
     * <p>
     * Так работает рециклотрон MOO II: он перерабатывает мусор, а мусорят все, не одни
     * рабочие. Эта прибавка ещё и не пачкает планету — грязь считается без неё, как и без
     * твёрдого производства зданий.
     */
    PRODUCTION_PER_COLONIST,

    /** Очки исследований за ход независимо от числа учёных. */
    RESEARCH_FLAT,

    /** Прибавка к очкам исследований с каждого учёного. */
    RESEARCH_PER_SCIENTIST,

    /** Прибавка к вместимости планеты в жителях. */
    MAX_POPULATION,

    /** Прибавка к приросту населения за ход в тысячах жителей. */
    POPULATION_GROWTH_K,

    /** Прибавка к налоговому доходу колонии в процентах. */
    INCOME_PERCENT,

    /**
     * Кредиты за ход сверх налога с жителей — п. 4.1.
     * <p>
     * «Special income» оригинала: золотые жилы дают колонии ровно пять кредитов, самоцветы
     * — десять, и от числа жителей это не зависит вовсе. Процентом такое не выражается:
     * на колонии в одного жителя процент от налога — это ноль.
     */
    INCOME_FLAT,

    /**
     * Прибавка к приросту населения в процентах — п. 7. Ею отличаются расы: плодовитые
     * растут вдвое быстрее, медленно растущие — вдвое медленнее.
     */
    GROWTH_PERCENT,

    /**
     * Процент к выработке фермера — п. 7. В MOO II так работают правительства и слабые
     * фермеры: объединение поднимает еду с фермера в полтора раза, плохие фермеры роняют
     * её на четверть (две единицы обращаются в полторы — целым числом это не записать).
     * Процент считается от выработки фермера, а не от еды колонии: еда со зданий вроде
     * гидропонной фермы идёт мимо него, как и в оригинале.
     */
    FOOD_PERCENT,

    /** Процент к выработке рабочего — п. 7: так поднимает производство объединение. */
    PRODUCTION_PERCENT,

    /**
     * Процент к выработке учёного — п. 7: демократия прибавляет половину, феодализм
     * отнимает её же. Лаборатории считаются отдельно и под процент не попадают —
     * в MOO II штраф феодализма тоже не трогает автоматическую науку зданий.
     */
    RESEARCH_PERCENT,

    /**
     * Сколько раз грязное производство делится пополам, прежде чем с него считают
     * уборку, — п. 10.
     * <p>
     * Так устроены очистные сооружения MOO II: с переработчиком отходов делитель грязи
     * равен двум, с атмосферным преобразователем — четырём, а с обоими — восьми
     * (StrategyWiki, Calculations). Поэтому здесь считаются <b>деления</b>, а не
     * проценты: они складываются, как складываются все прочие действия зданий (1 + 2 = 3,
     * то есть делитель 8), и оригинальные числа выходят сами собой. Процентами пришлось
     * бы перемножать, а этого набор действий колонии не умеет.
     */
    POLLUTION_HALVINGS,

    /**
     * Процент к терпимости планеты к грязи — п. 10: наноразборщики удваивают её (+100).
     * Считается от терпимости размера планеты.
     */
    POLLUTION_TOLERANCE_PERCENT,

    /**
     * Грязи нет вовсе — п. 10: свалка в ядре планеты убирает загрязнение целиком, и то же
     * умеет неприхотливая раса (п. 7). Количество здесь не значит ничего: хватает
     * наличия.
     */
    POLLUTION_NONE,

    /**
     * Процент к силе защитников колонии в наземном бою — п. 12: казармы и бронеказармы.
     * <p>
     * Только к ОБОРОНЕ: в MOO II нападающий приводит с собой морскую пехоту транспортами,
     * а казармы остаются дома — «the attacker is limited to Marines brought in using troop
     * transports, while the defender can employ both marines from marine barracks and armor
     * units from armor barracks». Считается от базовой силы бойца, как и расовая
     * подготовка, и складывается с ней одной строкой.
     */
    GROUND_DEFENCE_PERCENT
}
