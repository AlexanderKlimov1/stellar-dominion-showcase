package com.moo3.server.domain.enums;

/**
 * Что компонент даёт кораблю — п. 8.
 * <p>
 * Устроено как действие зданий ({@link BuildingEffectType}): пара «тип — количество»,
 * действия всех компонентов складываются. Поэтому новая пушка, броня или особый модуль —
 * это запись в {@code ship-components.json}, а не ветка в сервисе.
 */
public enum ShipEffectType {

    /** Урон одного выстрела. */
    WEAPON_DAMAGE,

    /** Выстрелов в залпе. */
    WEAPON_SHOTS,

    /** Броневые очки на единицу {@code system_factor} корпуса. */
    ARMOUR,

    /** Прибавка к броне в процентах — тяжёлая броня. */
    ARMOUR_PERCENT,

    /** Очки щита на единицу {@code system_factor} корпуса. */
    SHIELD,

    /** Скорость корабля в ГРЕ за ход. */
    SPEED,

    /**
     * Боевая скорость двигателя — п. 8, число оригинала: у ядерного двигателя MOO II она
     * равна двенадцати, и растёт с каждым следующим на четыре.
     * <p>
     * Поле боя переводит её в клетки делением на четыре: у нас оно двадцать клеток
     * шириной, а в MOO II много крупнее, и двенадцать клеток за ход пересекали бы его
     * целиком.
     */
    COMBAT_SPEED,

    /**
     * Очки уклонения <b>только от ракет</b> — п. 8: их сбивает постановщик помех, и
     * лучей со снарядами это не касается. В MOO II ECM Jammer именно этим и занят.
     */
    MISSILE_EVASION,

    /** Прибавка к залпу в процентах — прицельный компьютер, сканер, анализатор. */
    ATTACK_PERCENT,

    /** Прибавка к защите очками — постановщик помех, стабилизатор. */
    DEFENSE,

    /** Прибавка к прочности корпуса в процентах — усиленный корпус. */
    STRUCTURE_PERCENT,

    /** Прибавка к полезному месту корпуса в процентах — боевые отсеки. */
    SPACE_PERCENT,

    /**
     * Морская пехота на борту — п. 12. Наземный бой её пока не спрашивает: десант
     * считается от жителей колонии. Это точка расширения — когда {@code GroundCombatService}
     * научится брать войска с кораблей, число придёт отсюда.
     */
    TROOPS
}
