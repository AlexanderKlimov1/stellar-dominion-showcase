package com.moo3.server.domain.enums;

/**
 * Кто это в игре — п. 3.1.
 * <p>
 * Ролей две, и вторая нужна ради одной вещи: администратор существует до всякой
 * регистрации и не подтверждает почты — иначе первого входа в игру не случилось бы вовсе,
 * пока не настроен почтовый сервер.
 */
public enum AccountRole {

    /** Обычный игрок: регистрируется сам и подтверждает почту ссылкой из письма. */
    PLAYER,

    /** Администратор: заводится при первом запуске сервера, пароль лежит в admin.txt. */
    ADMIN;

    /** Ключ названия роли в словаре сервера — п. 3.5: показывается на языке игрока. */
    public String labelKey() {
        return "account.role." + name();
    }
}
