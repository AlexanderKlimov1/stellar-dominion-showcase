package com.moo3.server.domain.save;

import java.util.List;

/**
 * Флот в слепке партии — п. 8.
 * <p>
 * Владелец назван слотом, система — порядковым номером в списке систем слепка: при
 * загрузке и игроки, и звёзды заводятся заново и получают новые идентификаторы.
 * <p>
 * Встречи флотов в слепок не идут: встреча живёт один ход и ждёт решения игрока, а
 * загруженная партия начинается с начала хода — флоты в ней встретятся заново.
 */
public record FleetSnapshot(
        Integer ownerSlot,
        Integer systemIndex,
        Integer ships,
        Integer createdTurn,
        /**
         * Из каких проектов флот собран — п. 8; {@code null} в слепках, снятых до дизайна
         * кораблей: там корабль был безымянным.
         */
        List<FleetShipSnapshot> composition,

        /**
         * Куда флот летел, когда партию сохранили, — номер системы в списке слепка;
         * {@code null} — флот стоял на месте, а также во всех слепках, снятых до того, как
         * перелёт стал занимать ходы (п. 8).
         */
        Integer targetIndex,

        /** Ход вылета; {@code null} у стоящего флота. */
        Integer departureTurn,

        /** Ход прибытия; {@code null} у стоящего флота. */
        Integer arrivalTurn
) {
}
