package com.moo3.server.domain.enums;

/**
 * Какого рода лидер — п. 6.
 * <p>
 * В MOO II их два, и они не заменяют друг друга: колониальный служит в звёздной системе и
 * помогает её колониям, корабельный служит во флоте и помогает его кораблям. Мест у
 * империи по четыре на каждый род, и заняты они раздельно: полный набор губернаторов не
 * мешает нанять адмирала.
 */
public enum LeaderKind {

    /** Колониальный лидер: назначается в звёздную систему. */
    COLONY("Колониальный"),

    /** Корабельный лидер: назначается во флот. */
    SHIP("Корабельный");

    private final String label;

    LeaderKind(String label) {
        this.label = label;
    }

    public String getLabel() {
        return label;
    }
}
