package com.moo3.server.domain.enums;

/**
 * Что особенность расы меняет в игре — п. 7.
 * <p>
 * Часть особенностей действует на колонии, и их эффекты те же, что у зданий: колония
 * складывает их вместе и не различает, откуда взялась прибавка. Такие типы ссылаются
 * на свой {@link BuildingEffectType}. Остальные принадлежат своим подсистемам — бою,
 * шпионажу, кораблям, — и колония о них не знает вовсе.
 *
 * @see com.moo3.server.service.RaceTraitCatalog
 */
public enum RaceEffectType {

    /** Еда с фермера — действует на колонию. */
    FOOD_PER_FARMER(BuildingEffectType.FOOD_PER_FARMER),

    /** Производство с рабочего — действует на колонию. */
    PRODUCTION_PER_WORKER(BuildingEffectType.PRODUCTION_PER_WORKER),

    /** Очки исследований с учёного — действует на колонию. */
    RESEARCH_PER_SCIENTIST(BuildingEffectType.RESEARCH_PER_SCIENTIST),

    /** Процент к налоговому доходу — действует на колонию. */
    INCOME_PERCENT(BuildingEffectType.INCOME_PERCENT),

    /** Процент к приросту населения — действует на колонию. */
    GROWTH_PERCENT(BuildingEffectType.GROWTH_PERCENT),

    /** Процент к силе наземного боя — п. 12: и в нападении, и в обороне. */
    GROUND_COMBAT_PERCENT(null),

    /** Очки шпионажа за ход — п. 13. */
    ESPIONAGE_POINTS(null),

    /** Процент к атаке кораблей — п. 8. */
    SHIP_ATTACK_PERCENT(null),

    /** Процент к защите кораблей — п. 8. */
    SHIP_DEFENSE_PERCENT(null),

    /** Процент к выработке фермера — п. 7: объединение и плохие фермеры. */
    FOOD_PERCENT(BuildingEffectType.FOOD_PERCENT),

    /** Процент к выработке рабочего — п. 7: объединение. */
    PRODUCTION_PERCENT(BuildingEffectType.PRODUCTION_PERCENT),

    /** Процент к выработке учёного — п. 7: демократия и феодализм. */
    RESEARCH_PERCENT(BuildingEffectType.RESEARCH_PERCENT),

    /**
     * Очки контрразведки за ход — п. 13: сколько империя отнимает у чужого агента сверх
     * обычного. Отдельно от {@link #ESPIONAGE_POINTS} потому, что в MOO II правительства
     * дают перевес только в обороне: диктатура и объединение крепче держат своё, а
     * демократия слабее, — но чужие тайны от этого воровать не легче.
     */
    ESPIONAGE_DEFENSE_POINTS(null),

    /**
     * Процент к съедаемой жителем еде — п. 4.1.1: киборги едят вполовину меньше (−50),
     * литоворы не едят вовсе (−100).
     */
    FOOD_CONSUMPTION_PERCENT(null),

    /**
     * Процент производства, съедаемый жителем — п. 7: киборги проедают полпорции
     * производства вместо еды. Это цена, а не прибавка: колония отдаёт эту долю до того,
     * как считает стройку.
     */
    PRODUCTION_CONSUMPTION_PERCENT(null),

    /**
     * Прибавка к пригодной доле планеты в процентных пунктах — п. 4.1.2: неприхотливые
     * живут и в отравленном воздухе. Выше райской планеты доля не поднимается, поэтому
     * на Gaya прибавка не даёт ничего — как в MOO II.
     */
    HABITABILITY_PERCENT(null),

    /**
     * Загрязнения у расы нет вовсе — п. 7 и п. 10: неприхотливым отходы не мешают, и
     * убирать за собой им не приходится («Tolerant races also suffer no harm from
     * pollution and need not spend production resources cleaning it up»). Действует на
     * колонию, как вечная свалка в ядре планеты.
     */
    POLLUTION_NONE(BuildingEffectType.POLLUTION_NONE),

    /**
     * Прибавка к вместимости планеты за каждую ступень её размера — п. 4.1.1: подземные
     * получают два жителя на крошечной планете и десять на огромной.
     */
    MAX_POPULATION_PER_SIZE(null),

    /**
     * Водная раса — п. 4.1.2. Признак, а не число: мокрые климаты для неё считаются на
     * ступень-другую лучше, и это таблица, а не множитель. Таблица — в
     * {@link com.moo3.server.service.PopulationCalculator}.
     */
    AQUATIC(null),

    /** На сколько ступеней размера больше обычного родной мир — п. 7: большой мир. */
    HOME_SIZE_STEPS(null),

    /** На сколько ступеней богаче минералами родной мир — п. 7: богатый и бедный мир. */
    HOME_MINERALS_STEPS(null),

    /** Прибавка к очкам учёного на родном мире — п. 7: мир артефактов. */
    HOME_RESEARCH_PER_SCIENTIST(null),

    /** Процент к стоимости постройки кораблей — п. 8: феодализм строит на треть дешевле. */
    SHIP_COST_PERCENT(null),

    /** Прибавка к дальности хода флота в парсеках — п. 8: надпространственные. */
    SHIP_SPEED_PARSECS(null),

    /** Прибавка к скорости корабля на поле боя — п. 8: надпространственные. */
    SHIP_COMBAT_SPEED(null),

    /** Всевидящая раса — п. 15: вся галактика открыта с первого хода. */
    OMNISCIENT(null),

    /** Изобретательная раса — п. 9: уровень дерева даёт все свои технологии разом. */
    CREATIVE(null),

    /** Неизобретательная раса — п. 9: технологию уровня выбирает не игрок, а случай. */
    UNCREATIVE(null),

    /**
     * Процент к расположению чужих империй — п. 14.
     * <p>
     * Читается в {@code DiplomacyService}: доброе дело такой империи запоминают на
     * столько процентов лучше, а злое — на столько же слабее. У обаятельных это сотня
     * (вдвое сильнее доброе и вдвое слабее злое, как в MOO II), у телепатов четверть.
     */
    DIPLOMACY_PERCENT(null),

    /**
     * Процент к доходу с торговых договоров — п. 10, п. 15: прирождённые торговцы.
     * <p>
     * Отдельно от {@link #TRADE_INCOME_PERCENT}: тот про свои товары и лишнюю еду, этот
     * про договор с соседом. В MOO II это разные строки описания расы, и числа у них
     * разные — вдвое и на четверть.
     */
    TRADE_TREATY_PERCENT(null),

    /**
     * Процент к силе десанта <b>в обороне</b> — п. 12: подземные.
     * <p>
     * Отдельно от {@link #GROUND_COMBAT_PERCENT}, который считается и в нападении:
     * в MOO II подземная раса получает свою прибавку, «защищая колонию».
     */
    GROUND_DEFENCE_PERCENT(null),

    /**
     * Процент к запасу командных очков империи — п. 8, п. 14: Империум.
     * <p>
     * Читается в {@code CommandRules}: развитая диктатура содержит в полтора раза
     * больший флот, чем обычная.
     */
    COMMAND_PERCENT(null),

    /**
     * Насколько быстрее империя перевоспитывает подданных, в процентах — п. 7.
     * <p>
     * Положительное значит «быстрее»: у демократии и обаятельных это сотня (вдвое
     * быстрее), у объединения и отталкивающих минус половина (вдвое медленнее).
     * Складывается именно скорость — почему, объяснено в {@code AssimilationRules}.
     */
    ASSIMILATION_PERCENT(null),

    /**
     * Потерянная колония ассимилируется противником сразу — п. 7, п. 14: феодализм.
     * <p>
     * Признак жертвы, а не захватчика: в MOO II это слабость феодального строя, чьи
     * подданные переходят к победителю без сожалений. Читается при захвате колонии
     * в {@code GroundCombatService}.
     */
    INSTANT_ASSIMILATION(null),

    /**
     * Неприхотливая раса — п. 4.1.2: вместимость мира считается как на земном.
     * <p>
     * Это правило MOO II целиком («максимум колонистов всегда рассчитывается как на
     * планетах земного типа»), и процентом его не выразить: на ядовитом мире оно
     * поднимает пригодность с десятой доли до девяти десятых, а на райском не даёт ничего.
     */
    TOLERANT(null),

    /**
     * Кибернетическая раса — п. 8: корабли чинятся прямо в бою.
     * <p>
     * Читается в {@code TacticalBattleService}: между кругами корабль возвращает себе
     * десятую долю брони и корпуса, как в MOO II. Еду такая раса заменяет продукцией
     * отдельными эффектами ({@link #FOOD_CONSUMPTION_PERCENT} и
     * {@link #PRODUCTION_CONSUMPTION_PERCENT}).
     */
    CYBERNETIC(null),

    /**
     * Отталкивающая раса — п. 14, п. 15: договоров с ней не бывает, только война и мир.
     * <p>
     * Читается в {@code DiplomacyService.requireNotRepulsive}: договор, союз и дань такой
     * империи недоступны — ни предложить, ни принять.
     */
    REPULSIVE(null),

    /**
     * Обаятельная раса — п. 6, п. 7: лидеры приходят к ней чаще и нанимаются дешевле.
     * <p>
     * Зеркало отталкивающей. В MOO II это две стороны одной монеты: «у отталкивающей
     * выбор лидеров беднее, дороже и реже», обаятельная — наоборот. Читается в
     * {@code LeaderRules}: там же и числа. Прибавку к переговорам эта же особенность даёт
     * отдельным эффектом ({@link #DIPLOMACY_PERCENT}) — в оригинале она делает и то и
     * другое, и одним числом это не выразить.
     */
    CHARISMATIC(null),

    /**
     * Процент к доходу с торговли — п. 10: товары и лишняя еда идут вдвое дороже.
     * <p>
     * Читается на товарах колонии; надбавка к договорам о торговле — точка расширения
     * в {@code DiplomacyService}.
     */
    TRADE_INCOME_PERCENT(null),

    /**
     * Телепаты — п. 12: крупный корабль подчиняет колонию без десанта.
     * <p>
     * Читается в {@code ExpeditionService.mindControl}: правило MOO II целиком —
     * «вместо бомбёжки и вторжения раса берёт население планеты под свой контроль, если
     * на орбите есть корабль класса не ниже крейсера».
     */
    TELEPATHIC(null),

    /**
     * Скрытные корабли — п. 8: флот такой империи не виден чужим сканерам.
     * <p>
     * Читается в {@code ExplorationService.occupiedBy}: издали система с таким флотом
     * выглядит пустой. Вблизи — своя колония или свой флот в той же системе — он виден
     * как любой другой, и всевидящая раса замечает его всегда: «обнаруживает даже
     * невидимые корабли» — п. 7.
     */
    STEALTHY_SHIPS(null),

    /**
     * Везучая раса — п. 11.1: хорошие случайности чаще, плохие реже.
     * <p>
     * Читается в {@code GalacticEventService}: беда такую расу обходит стороной, а удача
     * тянется к ней первой.
     */
    LUCKY(null),

    /**
     * Военачальники — п. 7, п. 8: каждая колония даёт вдвое больше командных очков.
     * <p>
     * Читается в {@code CommandRules}: запас командных очков империи растёт с колониями,
     * а флот сверх запаса оплачивается казной. Опытные экипажи этой расы выражены
     * отдельными прибавками к атаке и защите кораблей — уровней подготовки команды
     * у здешних кораблей нет, и это точка расширения в {@code BattleRules}.
     */
    WARLORD(null),

    /**
     * Раса малой тяжести — п. 4.1: миры малой тяжести ей нипочём, обычные даются хуже.
     * <p>
     * Читается в {@code ColonyService}: тяжесть мира ({@link PlanetGravity}) роняет
     * производство колонии, если раса к ней не привыкла.
     */
    GRAVITY_LOW(null),

    /** Раса большой тяжести — п. 4.1: тяжёлые и обычные миры ей нипочём, лёгкие — нет. */
    GRAVITY_HIGH(null);

    private final BuildingEffectType colonyEffect;

    RaceEffectType(BuildingEffectType colonyEffect) {
        this.colonyEffect = colonyEffect;
    }

    /** Эффект колонии, которым эта особенность оборачивается; {@code null} — не колонии. */
    public BuildingEffectType getColonyEffect() {
        return colonyEffect;
    }
}
