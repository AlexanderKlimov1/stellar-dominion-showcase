package com.moo3.server.domain.enums;

/**
 * Случайные галактические события — п. 11.1, события MOO II.
 * <p>
 * В оригинале это «удачи, беды и напасти, случившиеся не по вине игрока», и в окне новой
 * игры их можно выключить. Список ниже — события MOO II, каждое со своим знаком: хорошее
 * достаётся отстающим, дурное бьёт по первому. Само правило оттуда же: «дурные события
 * чаще случаются с ведущими империями, а добрые — с теми, кто отстал», а раса «Везучие»
 * получает больше первых и не получает вторых.
 * <p>
 * Событие описано здесь только тем, что нужно выбору: знаком, весом и названием. Что оно
 * делает — в {@code GalacticEventService}: одно правило игры живёт в одном месте, а не
 * растекается по таблице и коду сразу.
 * <p>
 * <b>Чего из событий MOO II здесь нет:</b> космических чудищ (амёба, кристалл, дракон,
 * угорь, гидра) и налётов антаранцев — в игре нет ни монстров, ни антаранцев, и приделать
 * их событием значило бы завести половину подсистемы в фазе конца хода. Нет и событий с
 * длительностью — гиперпространственного шторма, чумы, демографического взрыва,
 * сверхновой: им нужна память о «сколько ещё ходов это длится», которой у партии пока
 * нет. Точка расширения одна и та же: новый вид сюда, его действие — в сервис.
 *
 * @param label   название события по-русски: его игрок видит в итогах хода
 * @param good    доброе ли событие: от этого зависит, кому оно достаётся
 * @param weight  вес в жребии среди событий своего знака: у частых он больше
 */
public enum GalacticEvent {

    /** «Древний корабль»: учёные империи разбирают находку и получают технологию. */
    ANCIENT_SHIP("Древний корабль", true, 3),

    /** «Тайный эксперимент»: открывается целый уровень раздела, а не одна технология. */
    SECRET_EXPERIMENT("Тайный эксперимент", true, 1),

    /** «Сдвиг оси»: климат колонии выправляется до земного. */
    AXIS_SHIFT("Сдвиг оси", true, 2),

    /** «Богатая жила»: недра колонии оказываются богаче, чем считалось. */
    MINERAL_DEPOSIT("Богатая жила", true, 3),

    /** «Пожертвование»: империи достаются деньги — наследство, находка, добрая воля. */
    DONATION("Пожертвование", true, 3),

    /** «Династический брак»: две империи становятся друг другу ближе. */
    DIPLOMATIC_MARRIAGE("Династический брак", true, 2),

    /** «Червоточина»: летящий флот оказывается у цели в этот же ход. */
    WORMHOLE("Червоточина", true, 2),

    /** «Компьютерный вирус»: текущее исследование приходится начинать заново. */
    COMPUTER_VIRUS("Компьютерный вирус", false, 3),

    /** «Пираты»: часть казны империи уходит налётчикам. */
    PIRATES("Пираты", false, 3),

    /** «Землетрясение»: колония теряет жителей и постройку. */
    EARTHQUAKE("Землетрясение", false, 3),

    /** «Промышленная авария»: климат колонии портится на ступень. */
    INDUSTRIAL_ACCIDENT("Промышленная авария", false, 2),

    /** «Истощение недр»: колония теряет в богатстве минералов. */
    MINERAL_DEPLETION("Истощение недр", false, 2),

    /** «Дипломатическое убийство»: две империи начинают доверять друг другу меньше. */
    DIPLOMATIC_ASSASSIN("Дипломатическое убийство", false, 2),

    /** «Взрыв корабля»: империя теряет один корабль. */
    EXPLODED_SHIP("Взрыв корабля", false, 2),

    /** «Воронка искривления»: летящий флот выбрасывает с курса, и он теряет ходы. */
    WARP_FUNNEL("Воронка искривления", false, 2);

    private final String label;
    private final boolean good;
    private final int weight;

    GalacticEvent(String label, boolean good, int weight) {
        this.label = label;
        this.good = good;
        this.weight = weight;
    }

    public String getLabel() {
        return label;
    }

    /** Доброе событие достаётся отстающим, дурное — ведущим (правило MOO II). */
    public Boolean getGood() {
        return good;
    }

    public Integer getWeight() {
        return weight;
    }
}
