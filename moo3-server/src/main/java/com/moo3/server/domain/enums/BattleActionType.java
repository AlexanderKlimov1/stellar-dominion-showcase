package com.moo3.server.domain.enums;

/**
 * Что корабль делает в свой ход — п. 8.
 * <p>
 * Как в MOO II: корабль сперва двигается, потом стреляет, и ход переходит следующему.
 * Движение хода не заканчивает — заканчивает выстрел или явный пропуск, поэтому
 * подойти и ударить можно за один свой ход.
 */
public enum BattleActionType {

    /** Перелёт в пределах скорости корабля; ход не заканчивает. */
    MOVE,

    /** Залп по цели в пределах дальности; ход заканчивает. */
    FIRE,

    /** Ничего не делать: ход переходит следующему кораблю. */
    PASS,

    /** Увести флот с поля: бой кончается, поле остаётся за противником. */
    RETREAT,

    /**
     * Самоподрыв — п. 8, кнопка SELF DESTRUCT оригинала.
     * <p>
     * Гарантированный взрыв своего корабля: он гибнет сам и бьёт всех, кто стоит рядом, —
     * и своих тоже. Подбитому кораблю, которому уже не уйти, это последнее, что он может
     * сделать по чужому строю.
     */
    SELF_DESTRUCT
}
