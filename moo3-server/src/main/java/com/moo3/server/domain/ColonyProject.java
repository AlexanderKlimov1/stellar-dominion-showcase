package com.moo3.server.domain;

import java.util.UUID;

/**
 * Что строит колония — п. 10.
 * <p>
 * Проект это либо код здания из справочника, либо один из особых проектов MOO II:
 * дома, товары и колониальная база. Ни один из них не становится зданием. Дома и товары
 * доступны с первого хода и не заканчиваются никогда — они превращают производство в
 * рождаемость и в деньги; колониальная база, наоборот, достраивается и заселяет соседнюю
 * планету своей системы.
 */
public final class ColonyProject {

    /**
     * Сколько проектов помещается в очередь стройки колонии — п. 10.
     * <p>
     * Семь, как в окне стройки MOO II: очередь там ограничена, и переполненная перестаёт
     * принимать новое («queue full» в руководстве к патчу 1.50). Восьмой проект колонии
     * не нужен: к тому времени, как дойдёт очередь, изучится половина дерева и строить
     * захочется другое.
     */
    public static final Integer QUEUE_LIMIT = 7;

    /** Дома: производство колонии идёт в прибавку к рождаемости. */
    public static final String HOUSING = "HOUSING";

    /** Товары: производство колонии продаётся и пополняет казну игрока. */
    public static final String TRADE_GOODS = "TRADE_GOODS";

    /**
     * Колониальная база: заселяет свободную планету той же системы — п. 4.1. Доступна,
     * пока в системе есть куда селиться; по готовности игрок выбирает планету.
     */
    public static final String COLONY_BASE = "COLONY_BASE";

    /**
     * Во что обходится колониальная база, единиц производства.
     * <p>
     * Число оригинала: StrategyWiki, страница Units — «Colony Base. Cost: 200». Раньше
     * здесь стояла реконструкция (100), сделанная, пока страница не открывалась.
     */
    public static final Integer COLONY_BASE_COST = 200;

    /**
     * Шпион — п. 13: колония готовит агента, и он поступает в распоряжение империи.
     * Исследований не требует: разведка — дело древнее и технологий не ждёт.
     */
    public static final String SPY = "SPY";

    /**
     * Во что обходится шпион, единиц производства.
     * <p>
     * Число оригинала: StrategyWiki, страница Units — «Spy. Cost: 100». Шпион там и
     * правда строится колонией, наравне с колониальной базой и грузовым флотом.
     */
    public static final Integer SPY_COST = 100;

    /**
     * Корабль — п. 8: колония строит боевой корабль, и он встаёт во флот своей системы.
     * Как и шпион, зданием не становится и исследований не требует: стартовый проект
     * империя умеет строить с первого хода.
     * <p>
     * Кораблей у империи столько же, сколько проектов, поэтому в списке доступного они
     * различаются кодом вида {@code SHIP:<идентификатор проекта>} — см. {@link #ship}.
     * Хранится это раздельно: код стройки у планеты остаётся {@code SHIP}, а проект —
     * в {@code project_design_id}.
     */
    public static final String SHIP = "SHIP";

    /** Разделитель кода стройки и проекта корабля. */
    private static final String SHIP_SEPARATOR = ":";

    /** Код стройки для конкретного проекта корабля — п. 8. */
    public static String ship(UUID designId) {
        return SHIP + SHIP_SEPARATOR + designId;
    }

    /** Строится ли корабль: и общий код, и код с проектом. */
    public static Boolean isShip(String projectCode) {
        return projectCode != null
                && (SHIP.equals(projectCode) || projectCode.startsWith(SHIP + SHIP_SEPARATOR));
    }

    /**
     * Проект из кода стройки; {@code null} — код без проекта. Так приходит выбор игрока
     * и так же читаются партии, начатые до появления подсистемы: у них код просто
     * {@code SHIP}, и проект им подбирает стройка.
     */
    public static UUID shipDesign(String projectCode) {
        if (projectCode == null || !projectCode.startsWith(SHIP + SHIP_SEPARATOR)) {
            return null;
        }
        return UUID.fromString(projectCode.substring(SHIP.length() + SHIP_SEPARATOR.length()));
    }

    /**
     * Грузовой флот — п. 4.1.1: корабли, которые возят еду между колониями империи.
     * <p>
     * Требует технологии «Freighters» (Power, уровень 1) — как в MOO II, где грузовики
     * появляются вместе с ней. Зданием не становится: готовый корабль уходит империи.
     */
    public static final String FREIGHTER = "FREIGHTER";

    /** Технология, открывающая грузовой флот, — код из дерева технологий. */
    public static final String FREIGHTER_TECH = "freighters";

    /**
     * Во что обходится грузовой флот, единиц производства.
     * <p>
     * Число оригинала: StrategyWiki, страница Units — «Freighter Fleet. Cost: 50».
     */
    public static final Integer FREIGHTER_COST = 50;

    /**
     * Колониальный корабль — п. 4.1: увозит поселенцев в чужую систему и основывает там
     * колонию. Тем и отличается от колониальной базы, которая селится по соседству.
     * <p>
     * Достроенный корабль встаёт во флот своей системы, как боевой, и дальше это обычный
     * корабль: летит с флотом, гибнет вместе с ним и высаживает колонию по приказу.
     */
    public static final String COLONY_SHIP = "COLONY_SHIP";

    /**
     * Технологии, открывающие гражданские корабли, — коды из дерева (Power, уровень 2
     * «Cold Fusion»).
     * <p>
     * Без них корабль в списке стройки не появляется вовсе. Раньше хватало умения строить
     * корабли вообще (базовые Power и Chemistry), и колониальный корабль можно было
     * заложить до того, как он изучен: империя расселялась технологией, которой у неё нет.
     * <p>
     * Уровень общий, поэтому все три приходят разом; кода всё равно три, а не один —
     * условие у каждого корабля своё, и правка дерева не должна молча открывать соседний.
     */
    public static final String COLONY_SHIP_TECH = "colony-ship";

    /**
     * Во что обходится колониальный корабль, единиц производства.
     * <p>
     * Число оригинала: StrategyWiki, страница Units — «Colony Ship. Cost: 500». Он и
     * должен быть дорогим: в MOO II ранняя империя строит его несколько десятков ходов,
     * и выбор «расселяться или вооружаться» на этом и держится.
     */
    public static final Integer COLONY_SHIP_COST = 500;

    /**
     * Корабль-застава — п. 8: ставит заставу на любой планете, включая пояса астероидов
     * и газовые гиганты, куда колония не встанет никогда.
     * <p>
     * Застава жителей не даёт и производства не приносит: она нужна ради дальности.
     * Топливо в MOO II меряется от своих миров, и застава считается своим миром, поэтому
     * ею империя дотягивается туда, куда сама долететь не могла.
     */
    public static final String OUTPOST_SHIP = "OUTPOST_SHIP";

    /** Технология, открывающая корабль-заставу, — см. {@link #COLONY_SHIP_TECH}. */
    public static final String OUTPOST_SHIP_TECH = "outpost-ship";

    /**
     * Во что обходится корабль-застава, единиц производства.
     * <p>
     * Число оригинала: StrategyWiki, страница Units — «Outpost Ship. Cost: 100».
     */
    public static final Integer OUTPOST_SHIP_COST = 100;

    /**
     * Транспорт — п. 12: везёт десант к чужой колонии в любой системе. До него десант
     * высаживался только внутри своей системы, и захватить соседа было нечем.
     */
    public static final String TRANSPORT = "TRANSPORT";

    /** Технология, открывающая транспорт, — см. {@link #COLONY_SHIP_TECH}. */
    public static final String TRANSPORT_TECH = "transport";

    /**
     * Во что обходится транспорт, единиц производства.
     * <p>
     * Число оригинала: StrategyWiki, страница Units — «Transport Ship. Cost: 100».
     */
    public static final Integer TRANSPORT_COST = 100;

    /**
     * Сколько бойцов везёт транспорт.
     * <p>
     * Число оригинала: там же — «Carries four marines». Десант здесь считается жителями
     * (п. 12), поэтому четыре бойца — это четыре единицы населения при высадке.
     */
    public static final Integer TRANSPORT_TROOPS = 4;

    /**
     * Сколько поселенцев привозит колониальный корабль.
     * <p>
     * Реконструкция: в MOO II новая колония начинается с одного жителя — с того же, с
     * чего начинается колония от колониальной базы. Число одно на оба пути расселения и
     * правится здесь.
     */
    public static final Integer COLONY_SHIP_SETTLERS = 1;

    private ColonyProject() {
    }

    /**
     * Особый проект не оставляет здания на планете; достраиваются из них база, шпион
     * и корабль.
     */
    public static Boolean isSpecial(String projectCode) {
        return HOUSING.equals(projectCode)
                || TRADE_GOODS.equals(projectCode)
                || COLONY_BASE.equals(projectCode)
                || SPY.equals(projectCode)
                || isShip(projectCode)
                || COLONY_SHIP.equals(projectCode)
                || OUTPOST_SHIP.equals(projectCode)
                || TRANSPORT.equals(projectCode)
                || FREIGHTER.equals(projectCode);
    }

    /**
     * Можно ли поставить проект в очередь ещё раз — п. 10.
     * <p>
     * Здание на планете стоит одно, второго такого же не построить. Всё остальное —
     * корабли, шпионы, грузовики, дома, товары и колониальные базы — повторяется сколько
     * угодно: в системе бывает не одна свободная планета, и заселять их по одной,
     * дожидаясь каждый раз своей очереди у списка стройки, игрок не должен. Готовая база
     * при этом по-прежнему одна: вторую колония достраивает только после того, как первая
     * пристроена (см. {@code ProductionPhase.buildColonyBase}).
     */
    public static Boolean repeatable(String projectCode) {
        return isSpecial(projectCode);
    }

    /**
     * Бесконечная стройка — п. 10: дома и товары не заканчиваются ни в оригинале, ни
     * здесь, и очереди такая стройка не уступает никогда.
     * <p>
     * Знать это нужно тому, кто ставит проект в голову очереди: за бесконечной стройкой
     * поставленное ждало бы вечно, поэтому оно занимает её место, а она уходит в очередь.
     */
    public static Boolean endless(String projectCode) {
        return HOUSING.equals(projectCode) || TRADE_GOODS.equals(projectCode);
    }
}
