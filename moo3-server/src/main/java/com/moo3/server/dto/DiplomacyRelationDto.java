package com.moo3.server.dto;

import java.util.List;
import java.util.UUID;

/**
 * Отношения с одной знакомой империей — п. 15.
 *
 * Доверия здесь два, и путать их нельзя: отношения хранятся двумя строками, и каждая
 * держит мнение своей стороны о другой. Решение всегда принимает тот, кому предлагают,
 * поэтому чужое доверие предсказывает ответ соседа на предложение игрока, а своё — то,
 * как ответил бы сам игрок, и оно же падает от чужих подлостей: украл шпион — доверия
 * к вору у пострадавшего убыло (п. 13).
 *
 * @param stance       состояние отношений кодом
 * @param stanceLabel  то же по-русски, для интерфейса
 * @param trust        доверие соседа к игроку, 0..100 — по нему сосед и решает, соглашаться ли
 * @param yourTrust    доверие игрока к соседу, 0..100 — его подтачивают чужие кражи и поимки
 * @param treaties     действующие договоры кодами
 * @param treatyLabels они же по-русски
 * @param character    характер и устремление правителя ИИ одной строкой — «Агрессивный
 *                     промышленник», как в окне Report меню рас MOO II; пусто у человека
 * @param metTurn      ход знакомства
 * @param answer       что ответила другая сторона на последнее действие; пусто — действие
 *                     согласия не требовало
 */
public record DiplomacyRelationDto(
        UUID playerId,
        String playerName,
        String raceName,
        String color,
        String stance,
        String stanceLabel,
        Integer trust,
        Integer yourTrust,
        List<String> treaties,
        List<String> treatyLabels,
        String character,
        Integer metTurn,
        String answer,
        /**
         * Ведутся ли с этой империей переговоры вообще — п. 15, п. 7.
         * <p>
         * Ложь, если отталкивающая раса хоть у одной из сторон: тогда в разговоре
         * остаются только война и мир, а договоров, дани, подарков и обмена не
         * существует. Экран по этому признаку и укорачивает список предложений — как в
         * оригинале, где у посла отталкивающей расы строк вчетверо меньше; иначе игрок
         * жал бы по очереди всё и получал отказ за отказом.
         */
        Boolean negotiates
) {
}
