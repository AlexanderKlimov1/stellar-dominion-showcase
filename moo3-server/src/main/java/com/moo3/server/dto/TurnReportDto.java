package com.moo3.server.dto;

import java.util.List;
import java.util.UUID;

/**
 * Что изменилось за ход у одного игрока — п. 11.1.
 * <p>
 * Отчёт приходит и в ответе на конец хода, и подпиской на события партии: ход считается,
 * когда закончили все, а значит для большинства игроков пересчёт случается «сам собой»,
 * без их запроса.
 * <p>
 * Списки изменившихся систем и планет нужны клиенту, чтобы не перечитывать всю галактику:
 * ему достаточно обновить то, что названо здесь. Пустые списки означают, что у игрока за
 * этот ход не изменилось ничего.
 *
 * @param turn             ход, который был пересчитан
 * @param events           события хода в порядке фаз: население, стройка, наука, шпионаж
 * @param changedSystemIds системы, где что-то изменилось у этого игрока
 * @param changedPlanetIds планеты, где что-то изменилось у этого игрока
 */
public record TurnReportDto(
        Integer turn,
        List<TurnEventDto> events,
        List<UUID> changedSystemIds,
        List<UUID> changedPlanetIds
) {
}
