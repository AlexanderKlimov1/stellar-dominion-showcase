package com.moo3.server.dto;

import java.util.List;

/**
 * Что можно обменять с одной знакомой империей — п. 15.
 * <p>
 * Обмен в MOO II это «моя технология за твою», поэтому окну нужны обе половины сразу:
 * чего нет у соседа (и что ему можно предложить) и чего нет у меня (и что можно у него
 * попросить). Обе считаются вычитанием: технологии, которые есть у одного и которых нет
 * у другого, — остальные в сделке бессмысленны, и показывать их значило бы предлагать
 * игроку заведомый отказ.
 *
 * @param offer  мои технологии, которых нет у соседа
 * @param wanted технологии соседа, которых нет у меня
 */
public record TechTradeDto(
        List<TechnologyOfferDto> offer,
        List<TechnologyOfferDto> wanted
) {

    /**
     * Технология в списке обмена.
     *
     * @param value ценность: стоимость уровня в очках исследований. По ней сходится
     *              сделка — сосед соглашается, когда получает не дешевле, чем отдаёт,
     *              и окно показывает это число, чтобы отказ не был неожиданностью
     */
    public record TechnologyOfferDto(
            String code,
            String name,
            String categoryCode,
            Integer levelOrder,
            Integer value
    ) {
    }
}
