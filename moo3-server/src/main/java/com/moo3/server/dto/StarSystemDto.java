package com.moo3.server.dto;

import java.util.List;
import java.util.UUID;

/**
 * Звёздная система на карте галактики — п. 3 / п. 11.3.
 * <p>
 * У неразведанной системы известны только положение и цвет звезды: название, планеты
 * и владелец приходят пустыми, пока система не разведана ({@code explored = false}).
 * Разведывают её только корабли — п. 15.
 * <p>
 * Сканеры империи добавляют к этому ровно один факт: попала ли система в их дальность
 * ({@code scanned}) и заметно ли там чужое присутствие ({@code occupied}) — чужая колония
 * или чужой флот. Состав системы сканер не раскрывает: за этим нужно лететь.
 */
public record StarSystemDto(
        UUID id,
        String name,
        Double x,
        Double y,
        String color,
        String colorHex,
        Boolean special,
        UUID ownerPlayerId,
        List<PlanetDto> planets,
        Boolean explored,

        /** Система в дальности сканеров империи — п. 15. */
        Boolean scanned,

        /** Сканер видит в системе чужое присутствие — п. 15; состав системы он не даёт. */
        Boolean occupied,

        /**
         * Космическое чудище, сторожащее систему, — п. 11.1; пусто — сторожа нет или его
         * не видно.
         * <p>
         * Видно чудище в разведанной системе, а ВСЕВИДЯЩЕЙ расе (п. 7) — в любой: её
         * сторона расы в том и состоит, что она знает галактику, не летая. Для неё это не
         * украшение карты, а настоящее преимущество: она обходит сторожей с первого хода,
         * а прочие узнают о них, потеряв колониальный корабль.
         */
        String monster
) {
}
