package com.moo3.server.service.stub;

import com.moo3.server.service.TurnContext;

/**
 * Фаза расчёта конца хода.
 * <p>
 * Каждая фаза — отдельный бин, порядок задаётся {@link #order()}: рост населения (5),
 * производство и доход (7), исследования (10), шпионаж (12). {@link TurnService}
 * подхватывает все реализации сам, так что новая фаза (движение флотов, дипломатия ИИ) —
 * это новый бин и ничего больше.
 * <p>
 * Галактику фаза не вычитывает: всё загруженное и посчитанное на этот ход лежит в
 * {@link TurnContext} — одна выборка на весь ход вместо выборки на каждую фазу. Туда же
 * фаза складывает, что изменилось у игроков: из этого собирается отчёт хода.
 */
public interface TurnPhase {

    /** Порядок применения: меньше — раньше. */
    Integer order();

    /** Название фазы для журнала хода. */
    String name();

    void apply(TurnContext context);
}
