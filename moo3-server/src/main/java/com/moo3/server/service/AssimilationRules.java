package com.moo3.server.service;

import com.moo3.server.domain.RaceEffects;
import org.springframework.stereotype.Service;

/**
 * Ассимиляция подданных — п. 7, п. 12.
 * <p>
 * В MOO II захваченная колония достаётся победителю вместе с жителями, и жители эти
 * остаются чужой расой: работают по своим правилам, пока не станут своими. Скорость
 * перевоспитания задаёт строй победителя и его обхождение с чужими:
 * <ul>
 *   <li>объединение — «один колонист за 20 ходов», самый медленный строй (число MOO II);</li>
 *   <li>демократия — «ассимиляция вдвое быстрее»;</li>
 *   <li>обаятельные — «скорость ассимиляции вдвое выше»;</li>
 *   <li>отталкивающие — «скорость падает вдвое»;</li>
 *   <li>феодализм — особый случай: <b>потерянная</b> им колония ассимилируется
 *       противником сразу, и подданных на ней не остаётся вовсе.</li>
 * </ul>
 * <p>
 * <b>Реконструкция.</b> Обычную скорость оригинал не называет — названы только «20 ходов
 * у объединения» и «вдвое быстрее у демократии». Отсюда обычные
 * {@link #BASE_TURNS_PER_COLONIST} ходов: объединение выходит ровно вдвое медленнее, а
 * демократия — вдвое быстрее, как и сказано.
 */
@Service
public class AssimilationRules {

    /** Сколько ходов уходит на одного подданного у обычной империи. <i>Реконструкция.</i> */
    public static final int BASE_TURNS_PER_COLONIST = 10;

    /**
     * Ниже какой доли обычной скорости перевоспитание не опускается: даже у отталкивающего
     * объединения подданные когда-нибудь становятся своими.
     */
    private static final int MIN_SPEED_PERCENT = 25;

    /**
     * За сколько ходов империя делает своим одного подданного — п. 7.
     * <p>
     * <b>Складывается скорость, а не время.</b> Особенности в MOO II ускоряют и замедляют
     * ассимиляцию в разы («вдвое быстрее», «вдвое медленнее»), и складывать проценты
     * времени нельзя: демократия с обаянием (каждая «вдвое быстрее») дали бы ноль ходов,
     * то есть мгновенное перевоспитание, которого в игре нет ни у кого, кроме феодальной
     * жертвы. Поэтому проценты идут в скорость: сотня — вдвое быстрее, минус половина —
     * вдвое медленнее, а время получается делением.
     */
    public Integer turnsPerColonist(RaceEffects race) {
        int speed = Math.max(MIN_SPEED_PERCENT, 100 + race.assimilationPercent());
        return Math.max(1, BASE_TURNS_PER_COLONIST * 100 / speed);
    }

    /**
     * Сколько жителей достаётся победителю подданными — п. 12.
     * <p>
     * <b>Реконструкция.</b> Бой здесь считают сами жители (десанта как отдельного рода
     * войск в игре нет), поэтому проигравшая сторона теряет тем больше, чем сильнее был
     * удар: уцелевшая доля — это отношение её силы к силе победителя, зеркало той доли,
     * которую сохраняет победитель. Вдвое более сильный захватчик оставляет половину
     * жителей, десятикратный — десятую часть.
     *
     * @param defenders    сколько жителей защищало колонию
     * @param defencePower их сила
     * @param attackPower  сила победителя; не меньше силы обороны, иначе колония не взята
     */
    public Integer subjects(Integer defenders, Integer defencePower, Integer attackPower) {
        if (defenders <= 0 || attackPower <= 0) {
            return 0;
        }
        return Math.max(0, (int) ((long) defenders * defencePower / attackPower));
    }
}
