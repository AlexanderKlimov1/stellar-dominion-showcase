package com.moo3.server.service;

import com.moo3.server.domain.entity.PlanetEntity;
import org.springframework.stereotype.Service;

/**
 * Мощь империи одним числом — п. 11.1, п. 15.
 * <p>
 * Сводная величина, по которой империи и сравнивают друг друга: она стоит первой линией
 * на графике окна «Инфо» и по ней же решают империи ИИ, нападать ли на соседа. Формула
 * одна на всю игру и правится только здесь — иначе игрок видел бы на графике одно, а
 * сосед считал бы другое.
 * <p>
 * <b>Что входит.</b> Флот, население, выработка колоний за ход и число изученных
 * технологий: всё, чем империя сильна. Казна не входит — деньги это не сила, а
 * возможность; колонии не входят отдельно — они уже посчитаны населением.
 * <p>
 * <i>Реконструкция:</i> MOO II показывает «график истории, на котором видно, как империя
 * игрока смотрится рядом с соперниками», но из чего складывается его величина, не
 * называет. Веса подобраны так, чтобы ни одна часть не забивала прочие: у стартовой
 * империи это восемь жителей (32), по восемь производства и науки (32) — доли
 * сопоставимые, а дальше растёт то, во что империя вкладывается.
 * <p>
 * <b>Проверять это правило надо не на первом ходу, а на всей партии.</b> Веса и были
 * выверены на первом — когда флота ещё нет, — и флот оттого вошёл в сумму БЕЗ множителя.
 * Один линкор весил 1083 при всей стартовой империи в 144; см. {@link #PER_FLEET_POWER}.
 */
@Service
public class EmpireMightRules {

    /** Житель — как небольшой корабль: население и есть то, из чего берётся всё прочее. */
    private static final int PER_POPULATION = 4;

    /** Единица выработки за ход — вдвое: она приносит себя каждый ход, а не один раз. */
    private static final int PER_PRODUCTION = 2;
    private static final int PER_RESEARCH = 2;

    /** Изученная технология — разом за десятерых: за ней стоят сотни очков исследований. */
    private static final int PER_TECHNOLOGY = 10;

    /**
     * Во сколько раз сила флота ТЯЖЕЛЕЕ прочего, и потому делится — п. 11.1 (журнал, п. 3.75).
     * <p>
     * <b>Чего здесь не хватало.</b> У всех слагаемых мощи есть множитель, а у флота его не
     * было вовсе: он входил сырым. Веса подобраны так, «чтобы ни одна часть не забивала
     * прочие в начале партии», — но выверены они на ПЕРВОМ ходу, когда флота ещё нет, и
     * проверить перекос было нечем. Измерено летописью: один линкор стоил 1083 мощи при
     * том, что вся стартовая империя — 144, а всё хозяйство той же империи на 150-м ходу
     * (население, выработка, наука и двадцать технологий вместе) — 444. Один корабль весил
     * вдвое больше всего, что империя построила за партию.
     * <p>
     * Разрыв к тому же РАСШИРЯЕТСЯ: сила корабля это произведение трёх величин
     * ({@code урон × живучесть × (100 + защита)}), она растёт с технологиями
     * мультипликативно, а население и выработка — линейно.
     * <p>
     * <b>Десять — чтобы корабль весил примерно как колония, которая его построила.</b>
     * Линкор выходит 108 против сотни у населения той же империи, и флот занимает пятую
     * часть мощи вместо трёх четвертей. Это та же мера «ни одна часть не забивает прочие»,
     * только применённая ко всей партии, а не к первому ходу.
     * <p>
     * <i>Чем это важно за пределами графика:</i> по мощи империи ИИ решают, нападать ли
     * (п. 15), и к ведущей по мощи тянутся беды галактических событий (п. 11.1). Пока флот
     * весил три четверти, империя, вложившаяся в хозяйство, числилась слабейшей — и
     * получала и то, и другое.
     */
    private static final int PER_FLEET_POWER = 10;

    /**
     * Мощь империи из её замера — п. 11.1.
     *
     * @param populationK население в тысячах, как оно и хранится у колонии
     */
    public Integer might(Integer fleetPower, Integer populationK, Integer production,
                         Integer research, Integer technologies) {
        return fleetPower / PER_FLEET_POWER
                + populationK / PlanetEntity.POPULATION_UNIT * PER_POPULATION
                + production * PER_PRODUCTION
                + research * PER_RESEARCH
                + technologies * PER_TECHNOLOGY;
    }
}
